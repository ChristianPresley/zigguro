//! Renders the budget registry as `docs/perf/budgets.md`: one table per
//! owning epic, numbers with SI units.

const std = @import("std");
const schema = @import("schema.zig");

/// The first line of the generated document.
pub const header = "<!-- Generated by `zig build budgets-doc`; do not edit. Source: packages/perf/budgets.zon -->\n";

/// Writes `value` in `metric`'s unit with an SI prefix (`8 ms`, `150 MB`,
/// `2 GB/s`, `64 MiB` for exact binary multiples).
pub fn writeValue(w: *std.Io.Writer, metric: schema.Metric, value: f64) std.Io.Writer.Error!void {
    switch (metric) {
        .duration_ns => {
            const units = [_]struct { f64, []const u8 }{ .{ 1e9, "s" }, .{ 1e6, "ms" }, .{ 1e3, "µs" } };
            for (units) |u| if (value >= u[0]) return w.print("{d} {s}", .{ trim(value / u[0]), u[1] });
            return w.print("{d} ns", .{trim(value)});
        },
        .bytes => {
            const bin = [_]struct { f64, []const u8 }{ .{ 1 << 30, "GiB" }, .{ 1 << 20, "MiB" }, .{ 1 << 10, "KiB" } };
            for (bin) |u| if (value >= u[0] and @mod(value, u[0]) == 0) return w.print("{d} {s}", .{ value / u[0], u[1] });
            return writeDecimal(w, value, "B");
        },
        .bytes_per_second => return writeDecimal(w, value, "B/s"),
        .per_second => return writeDecimal(w, value, "/s"),
        .percent => return w.print("{d} %", .{trim(value)}),
        .count => return writeDecimal(w, value, ""),
    }
}

fn writeDecimal(w: *std.Io.Writer, value: f64, unit: []const u8) std.Io.Writer.Error!void {
    const units = [_]struct { f64, []const u8 }{ .{ 1e9, "G" }, .{ 1e6, "M" }, .{ 1e3, "k" } };
    for (units) |u| if (value >= u[0]) {
        return w.print("{d} {s}{s}", .{ trim(value / u[0]), u[1], unit });
    };
    if (unit.len == 0) return w.print("{d}", .{trim(value)});
    if (unit[0] == '/') return w.print("{d}{s}", .{ trim(value), unit });
    return w.print("{d} {s}", .{ trim(value), unit });
}

/// Rounds to 3 significant decimals to hide float noise (0.30000000004).
fn trim(v: f64) f64 {
    return @round(v * 1000) / 1000;
}

fn writeSource(w: *std.Io.Writer, s: schema.Source) std.Io.Writer.Error!void {
    switch (s) {
        .bench => |b| try w.print("bench `{s}` / `{s}` ({t})", .{ b.suite, b.name, b.field }),
        .scenario => |sc| try w.print("scenario `{s}` / `{s}`", .{ sc.name, sc.metric }),
        .runtime => |r| try w.print("runtime `{s}`", .{r}),
    }
}

fn lessOwner(_: void, a: []const u8, b: []const u8) bool {
    return std.mem.order(u8, a, b) == .lt;
}

/// Writes the whole document for `f`.
pub fn writeMarkdown(f: *const schema.File, w: *std.Io.Writer) std.Io.Writer.Error!void {
    try w.writeAll(header);
    try w.writeAll("\n# Performance budgets\n\n");
    try w.print("{d} budgets. Limits are hard; targets are goals. `machine = any` rows are machine-independent. CI hosted runners gate only relative regressions (see `docs/perf/benchmarks.md`). How the UI thread stays within these: [threading.md](threading.md).\n", .{f.budgets.len});
    try w.writeAll("\n## Machines\n\n| class | description | cpu | RAM | gpu | display |\n|---|---|---|---|---|---|\n");
    for (f.machines) |m| try w.print("| `{t}` | {s} | {s} | {d} GB | {s} | {s} |\n", .{ m.class, m.description, m.cpu, m.ram_gb, m.gpu, m.display });

    // Owners in sorted order, each once.
    var owners: [100]bool = @splat(false);
    for (f.budgets) |b| {
        if (b.owner.len == 3) owners[(b.owner[1] - '0') * 10 + (b.owner[2] - '0')] = true;
    }
    for (owners, 0..) |present, n| {
        if (!present) continue;
        try w.print("\n## E{d:0>2}\n\n| id | metric | stat | limit | target | machine | source | gate | spec |\n|---|---|---|---|---|---|---|---|---|\n", .{n});
        for (f.budgets) |b| {
            if (b.owner.len != 3 or (b.owner[1] - '0') * 10 + (b.owner[2] - '0') != n) continue;
            try w.print("| `{s}` | {t} | {t} | ", .{ b.id, b.metric, b.stat });
            if (b.direction == .higher_is_better) try w.writeAll("≥ ");
            try writeValue(w, b.metric, b.limit);
            try w.writeAll(" | ");
            if (b.target) |t| try writeValue(w, b.metric, t) else try w.writeAll("–");
            try w.print(" | {t} | ", .{b.machine});
            try writeSource(w, b.source);
            try w.print(" | {t} | {s} |\n", .{ b.gate, b.spec });
        }
    }
}

test "budget: docgen golden" {
    const f: schema.File = .{
        .schema = 1,
        .machines = &.{.{ .class = .ref_laptop_2024, .description = "ref", .cpu = "8C/16T", .ram_gb = 16, .gpu = "iGPU", .display = "2560x1600@120" }},
        .budgets = &.{
            .{ .id = "input.key_to_photon", .owner = "E14", .spec = "CONVENTIONS", .metric = .duration_ns, .stat = .p99, .limit = 8e6, .target = 5e6, .source = .{ .scenario = .{ .name = "latency", .metric = "p99" } } },
            .{ .id = "sse.parse", .owner = "E00", .spec = "E00.F06", .metric = .bytes_per_second, .stat = .mean, .direction = .higher_is_better, .limit = 500e6, .source = .{ .bench = .{ .suite = "zg_net", .name = "sse", .field = .throughput_bps } }, .gate = .warn },
            .{ .id = "mem.gpu", .owner = "E14", .spec = "E02", .metric = .bytes, .stat = .max, .limit = 96 * 1024 * 1024, .source = .{ .runtime = "pending" }, .gate = .track },
            .{ .id = "idle.wakeups", .owner = "E14", .spec = "CONVENTIONS", .metric = .per_second, .stat = .mean, .limit = 0.5, .machine = .any, .source = .{ .runtime = "idle" } },
        },
    };
    var out: std.Io.Writer.Allocating = .init(std.testing.allocator);
    defer out.deinit();
    try writeMarkdown(&f, &out.writer);
    try std.testing.expectEqualStrings(@embedFile("../testdata/budgets_fixture.md"), out.written());
}

test "budget: docgen units" {
    var buf: [64]u8 = undefined;
    var w: std.Io.Writer = .fixed(&buf);
    try writeValue(&w, .duration_ns, 150e6);
    try writeValue(&w, .bytes, 150e6);
    try writeValue(&w, .bytes_per_second, 2e9);
    try writeValue(&w, .duration_ns, 20);
    try std.testing.expectEqualStrings("150 ms150 MB2 GB/s20 ns", w.buffered());
}
