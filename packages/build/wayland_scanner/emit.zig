//! Emits Zig source for a set of protocols. Every interface becomes a
//! struct with `name`, `version`, an `Id` enum, its enums, `Request` and
//! `Event` unions, client request encoders, server-side event encoders
//! (`server`, used by test compositors), and `decodeEvent` /
//! `decodeRequest`, which return zero-copy views into the message body.
//!
//! Encoders call `conn.send(object, opcode, args_tuple, fds)`; decoders
//! pop fds from `fds.pop() ?i32`. The output is self-contained (it imports
//! only std), so the wire layer and tests share it.

const std = @import("std");
const model = @import("model.zig");

const W = *std.Io.Writer;
const Error = std.Io.Writer.Error || std.mem.Allocator.Error;

/// Writes the generated source for `protos` (from files named `sources`).
/// `gpa` should be an arena: scratch strings are not freed one by one.
pub fn emit(gpa: std.mem.Allocator, w: W, protos: []const model.Protocol, sources: []const []const u8) Error!void {
    var e: Emitter = .{ .gpa = gpa, .w = w, .protos = protos };
    try e.file(sources);
}

const Emitter = struct {
    gpa: std.mem.Allocator,
    w: W,
    protos: []const model.Protocol,

    fn findInterface(e: *const Emitter, name: []const u8) ?*const model.Interface {
        for (e.protos) |p| for (p.interfaces) |*i| if (std.mem.eql(u8, i.name, name)) return i;
        return null;
    }

    fn file(e: *Emitter, sources: []const []const u8) Error!void {
        const w = e.w;
        try w.writeAll("//! Generated by wayland_scanner from");
        for (sources, 0..) |s, i| try w.print("{s} {s}", .{ if (i == 0) "" else ",", std.fs.path.basename(s) });
        try w.writeAll(".\n//! Do not edit.\n\n");
        try w.writeAll(prelude);
        for (e.protos) |p| for (p.interfaces) |*i| try e.interface(i);
        try w.writeAll("/// Every interface, in protocol order.\npub const interfaces = [_]type{\n");
        for (e.protos) |p| for (p.interfaces) |i| try w.print("    {f},\n", .{std.zig.fmtId(i.name)});
        try w.writeAll("};\n\ntest {\n    inline for (interfaces) |I| std.testing.refAllDecls(I);\n}\n");
    }

    fn doc(e: *Emitter, indent: []const u8, summary: ?[]const u8, description: ?[]const u8) Error!void {
        const w = e.w;
        const sum: ?[]const u8 = if (summary) |s| (if (std.mem.trim(u8, s, " \t\r\n").len == 0) null else s) else null;
        if (sum) |s| try w.print("{s}/// {f}\n", .{ indent, oneLine(s) });
        if (description) |d| {
            if (sum != null) try w.print("{s}///\n", .{indent});
            var it = std.mem.splitScalar(u8, d, '\n');
            var blank = false;
            while (it.next()) |line| {
                const t = std.mem.trim(u8, line, " \t\r");
                if (t.len == 0) {
                    blank = true;
                    continue;
                }
                if (blank) try w.print("{s}///\n", .{indent});
                blank = false;
                try w.print("{s}/// {s}\n", .{ indent, t });
            }
        }
    }

    fn interface(e: *Emitter, i: *const model.Interface) Error!void {
        const w = e.w;
        try e.doc("", i.summary, i.description);
        if (i.summary == null and i.description == null) try w.print("/// The `{s}` interface.\n", .{i.name});
        try w.print("pub const {f} = struct {{\n", .{std.zig.fmtId(i.name)});
        try w.print("    /// The interface name on the wire.\n    pub const name = \"{s}\";\n", .{i.name});
        try w.print("    /// The highest version this code knows.\n    pub const version = {d};\n", .{i.version});
        try w.writeAll("    /// An object id of this interface.\n    pub const Id = enum(u32) { _ };\n");

        // Names declared in this struct: parameters must not shadow them.
        var taken: std.StringHashMapUnmanaged(void) = .empty;
        for ([_][]const u8{ "name", "version", "Id", "Request", "Event", "server", "decode", "decodeEvent", "decodeRequest", "request_destructors", "event_destructors", "conn", "self", "fds", "std", "Fixed", "DecodeError", "Reader" }) |n| try putTaken(e.gpa, &taken, n);
        for (e.protos) |p| for (p.interfaces) |x| try putTaken(e.gpa, &taken, x.name);
        for (i.enums) |en| try putTakenOwned(e.gpa, &taken, try e.enumTypeName(en.name));
        for (i.requests) |m| try putTakenOwned(e.gpa, &taken, try camel(e.gpa, m.name));
        for (i.events) |m| try putTakenOwned(e.gpa, &taken, try camel(e.gpa, m.name));

        for (i.enums) |*en| try e.enumeration(en);
        try e.messageUnion(i, "Request", i.requests);
        try e.messageUnion(i, "Event", i.events);
        try e.destructors("request_destructors", i.requests);
        try e.destructors("event_destructors", i.events);

        for (i.requests, 0..) |*m, op| try e.encoder(i, m, op, "    ", true, &taken);
        try w.writeAll("    /// Event encoders for the compositor side (test compositors).\n");
        if (i.events.len == 0) {
            try w.writeAll("    pub const server = struct {};\n");
        } else {
            try w.writeAll("    pub const server = struct {\n");
            for (i.events, 0..) |*m, op| try e.encoder(i, m, op, "        ", false, &taken);
            try w.writeAll("    };\n");
        }
        try e.decoder(i, "decodeEvent", "Event", i.events);
        try e.decoder(i, "decodeRequest", "Request", i.requests);
        try w.writeAll("    /// Decodes an event: the client side.\n    pub const decode = decodeEvent;\n");
        try w.writeAll("};\n\n");
    }

    fn enumTypeName(e: *Emitter, enum_name: []const u8) Error![]u8 {
        const c = try pascal(e.gpa, enum_name);
        for ([_][]const u8{ "Id", "Request", "Event" }) |bad| if (std.mem.eql(u8, c, bad)) {
            defer e.gpa.free(c);
            return std.fmt.allocPrint(e.gpa, "{s}Enum", .{c});
        };
        return c;
    }

    fn isPackable(en: *const model.Enum) bool {
        if (!en.bitfield) return false;
        var seen: u32 = 0;
        for (en.entries) |x| {
            if (x.value == 0) continue;
            if (@popCount(x.value) != 1 or seen & x.value != 0) return false;
            seen |= x.value;
        }
        return seen != 0;
    }

    fn enumeration(e: *Emitter, en: *const model.Enum) Error!void {
        const w = e.w;
        const tname = try e.enumTypeName(en.name);
        defer e.gpa.free(tname);
        try e.doc("    ", en.summary, en.description);
        if (en.summary == null and en.description == null) try w.print("    /// The `{s}` enum.\n", .{en.name});
        if (isPackable(en)) {
            try w.print("    pub const {s} = packed struct(u32) {{\n", .{tname});
            var bit: u6 = 0;
            var pad_start: ?u6 = null;
            while (bit < 32) : (bit += 1) {
                const v = @as(u32, 1) << @intCast(bit);
                const entry = for (en.entries) |x| {
                    if (x.value == v) break x;
                } else null;
                if (entry) |x| {
                    if (pad_start) |ps| try w.print("        _pad{d}: u{d} = 0,\n", .{ ps, bit - ps });
                    pad_start = null;
                    if (x.summary) |s| try w.print("        /// {f}\n", .{oneLine(s)});
                    try w.print("        {f}: bool = false,\n", .{std.zig.fmtIdP(x.name)});
                } else if (pad_start == null) pad_start = bit;
            }
            if (pad_start) |ps| try w.print("        _pad{d}: u{d} = 0,\n", .{ ps, 32 - @as(u32, ps) });
            try w.writeAll("    };\n");
            return;
        }
        try w.print("    pub const {s} = enum(u32) {{\n", .{tname});
        var aliases: std.ArrayList(struct { name: []const u8, of: []const u8 }) = .empty;
        defer aliases.deinit(e.gpa);
        for (en.entries, 0..) |x, idx| {
            const dup = for (en.entries[0..idx]) |prev| {
                if (prev.value == x.value) break prev.name;
            } else null;
            if (dup) |of| {
                try aliases.append(e.gpa, .{ .name = x.name, .of = of });
                continue;
            }
            if (x.summary) |s| try w.print("        /// {f}\n", .{oneLine(s)});
            try w.print("        {f} = {d},\n", .{ std.zig.fmtIdP(x.name), x.value });
        }
        try w.writeAll("        _,\n");
        for (aliases.items) |a| try w.print("        /// Same value as `{s}`.\n        pub const {f}: @This() = .{f};\n", .{ a.of, std.zig.fmtId(a.name), std.zig.fmtIdP(a.of) });
        try w.writeAll("    };\n");
    }

    /// The Zig type of an argument, or null for fds (which travel apart).
    fn argType(e: *Emitter, i: *const model.Interface, a: *const model.Arg) Error![]const u8 {
        switch (a.type) {
            .int, .uint => if (a.enum_ref) |ref| {
                if (try e.enumRef(i, ref)) |t| return t;
                return if (a.type == .int) "i32" else "u32";
            } else return if (a.type == .int) "i32" else "u32",
            .fixed => return "Fixed",
            .string => return if (a.allow_null) "?[:0]const u8" else "[:0]const u8",
            .array => return "[]const u8",
            .fd => return "i32",
            .object, .new_id => {
                if (a.interface) |iface| if (e.findInterface(iface) != null) {
                    return std.fmt.allocPrint(e.gpa, "{s}{f}.Id", .{ if (a.allow_null) "?" else "", std.zig.fmtId(iface) });
                };
                return if (a.allow_null) "?u32" else "u32";
            },
        }
    }

    fn enumRef(e: *Emitter, i: *const model.Interface, ref: []const u8) Error!?[]const u8 {
        var iface = i;
        var ename = ref;
        if (std.mem.indexOfScalar(u8, ref, '.')) |dot| {
            iface = e.findInterface(ref[0..dot]) orelse return null;
            ename = ref[dot + 1 ..];
        }
        for (iface.enums) |*en| if (std.mem.eql(u8, en.name, ename)) {
            const t = try e.enumTypeName(en.name);
            defer e.gpa.free(t);
            return try std.fmt.allocPrint(e.gpa, "{f}.{s}", .{ std.zig.fmtId(iface.name), t });
        };
        return null;
    }

    fn enumIsPacked(e: *Emitter, i: *const model.Interface, ref: []const u8) bool {
        var iface = i;
        var ename = ref;
        if (std.mem.indexOfScalar(u8, ref, '.')) |dot| {
            iface = e.findInterface(ref[0..dot]) orelse return false;
            ename = ref[dot + 1 ..];
        }
        for (iface.enums) |*en| if (std.mem.eql(u8, en.name, ename)) return isPackable(en);
        return false;
    }

    fn untypedNewId(a: *const model.Arg) bool {
        return a.type == .new_id and a.interface == null;
    }

    fn messageUnion(e: *Emitter, i: *const model.Interface, comptime which: []const u8, msgs: []const model.Message) Error!void {
        const w = e.w;
        try w.print("    /// The {s}s of `{s}`, tagged by opcode.\n", .{ if (std.mem.eql(u8, which, "Request")) "request" else "event", i.name });
        if (msgs.len == 0) {
            try w.print("    pub const {s} = union(enum(u16)) {{}};\n", .{which});
            return;
        }
        try w.print("    pub const {s} = union(enum(u16)) {{\n", .{which});
        for (msgs) |*m| {
            try e.doc("        ", m.summary, null);
            if (m.args.len == 0) {
                try w.print("        {f},\n", .{std.zig.fmtIdP(m.name)});
                continue;
            }
            try w.print("        {f}: struct {{", .{std.zig.fmtIdP(m.name)});
            var first = true;
            for (m.args) |*a| {
                if (untypedNewId(a)) {
                    try w.print("{s} interface: [:0]const u8, interface_version: u32, {f}: u32", .{ if (first) "" else ",", std.zig.fmtIdP(a.name) });
                } else {
                    try w.print("{s} {f}: {s}", .{ if (first) "" else ",", std.zig.fmtIdP(a.name), try e.argType(i, a) });
                }
                first = false;
            }
            try w.writeAll(" },\n");
        }
        try w.writeAll("    };\n");
    }

    fn destructors(e: *Emitter, comptime name: []const u8, msgs: []const model.Message) Error!void {
        var vals: std.ArrayList([]const u8) = .empty;
        for (msgs) |m| try vals.append(e.gpa, if (m.destructor) "true" else "false");
        try e.w.print("    /// Which opcodes destroy the object.\n    pub const {s} = [_]bool{f};\n", .{ name, tuple(vals.items) });
    }

    fn paramName(e: *Emitter, taken: *const std.StringHashMapUnmanaged(void), name: []const u8) Error![]const u8 {
        if (taken.contains(name)) return std.fmt.allocPrint(e.gpa, "{s}_", .{name});
        return std.fmt.allocPrint(e.gpa, "{f}", .{std.zig.fmtId(name)});
    }

    fn encoder(e: *Emitter, i: *const model.Interface, m: *const model.Message, op: usize, indent: []const u8, client: bool, taken: *const std.StringHashMapUnmanaged(void)) Error!void {
        const w = e.w;
        try e.doc(indent, m.summary, m.description);
        if (m.summary == null and m.description == null) try w.print("{s}/// Sends `{s}`.\n", .{ indent, m.name });
        const fname = try camel(e.gpa, m.name);
        defer e.gpa.free(fname);
        try w.print("{s}pub fn {f}(conn: anytype, self: Id", .{ indent, std.zig.fmtId(fname) });
        for (m.args) |*a| {
            const p = try e.paramName(taken, a.name);
            if (untypedNewId(a)) {
                try w.print(", interface: [:0]const u8, interface_version: u32, {s}: u32", .{p});
            } else try w.print(", {s}: {s}", .{ p, try e.argType(i, a) });
        }
        try w.writeAll(") !void {\n");
        if (client and m.since > 1) try w.print("{s}    if (std.debug.runtime_safety) conn.checkSince(@intFromEnum(self), {d});\n", .{ indent, m.since });
        var vals: std.ArrayList([]const u8) = .empty;
        var fd_vals: std.ArrayList([]const u8) = .empty;
        for (m.args) |*a| {
            const p = try e.paramName(taken, a.name);
            if (a.type == .fd) {
                try fd_vals.append(e.gpa, p);
            } else if (untypedNewId(a)) {
                try vals.appendSlice(e.gpa, &.{ "interface", "interface_version", p });
            } else try vals.append(e.gpa, p);
        }
        try w.print("{s}    try conn.send(@intFromEnum(self), {d}, .{f}, &.{f});\n", .{ indent, op, tuple(vals.items), tuple(fd_vals.items) });
        if (client and m.destructor) try w.print("{s}    conn.destroyed(@intFromEnum(self));\n", .{indent});
        try w.print("{s}}}\n", .{indent});
    }

    fn readExpr(e: *Emitter, i: *const model.Interface, a: *const model.Arg) Error![]const u8 {
        return switch (a.type) {
            .int => if (a.enum_ref) |ref| (if (try e.enumRef(i, ref)) |t| try std.fmt.allocPrint(e.gpa, "try r.enumeration({s})", .{t}) else "try r.int()") else "try r.int()",
            .uint => if (a.enum_ref) |ref| (if (try e.enumRef(i, ref)) |t|
                try std.fmt.allocPrint(e.gpa, "try r.{s}({s})", .{ if (e.enumIsPacked(i, ref)) "bits" else "enumeration", t })
            else
                "try r.word()") else "try r.word()",
            .fixed => "try r.fixed()",
            .string => if (a.allow_null) "try r.optString()" else "try r.string()",
            .array => "try r.array()",
            .fd => "try popFd(fds)",
            .object, .new_id => blk: {
                const t = try e.argType(i, a);
                if (std.mem.eql(u8, t, "u32")) break :blk if (a.type == .new_id) "try r.nonZero()" else "try r.word()";
                if (std.mem.eql(u8, t, "?u32")) break :blk "try r.optWord()";
                if (a.allow_null) break :blk try std.fmt.allocPrint(e.gpa, "try r.optObject({s})", .{t[1..]});
                break :blk try std.fmt.allocPrint(e.gpa, "try r.object({s})", .{t});
            },
        };
    }

    fn decoder(e: *Emitter, i: *const model.Interface, comptime fname: []const u8, comptime union_name: []const u8, msgs: []const model.Message) Error!void {
        const w = e.w;
        try w.print("    /// Decodes {s} body `body` (words after the header); strings and\n    /// arrays are views into it. `fds` provides `pop() ?i32`.\n", .{if (std.mem.eql(u8, union_name, "Event")) "an event" else "a request"});
        try w.print("    pub fn {s}(opcode: u16, body: []const u32, fds: anytype) DecodeError!{s} {{\n", .{ fname, union_name });
        if (msgs.len == 0) {
            try w.writeAll("        _ = opcode;\n        _ = body;\n        _ = fds;\n        return error.Protocol;\n    }\n");
            return;
        }
        var uses_fds = false;
        for (msgs) |m| for (m.args) |a| {
            if (a.type == .fd) uses_fds = true;
        };
        try w.writeAll("        var r: Reader = .{ .body = body };\n");
        if (!uses_fds) try w.writeAll("        _ = fds;\n");
        try w.writeAll("        switch (opcode) {\n");
        for (msgs, 0..) |*m, op| {
            try w.print("            {d} => {{\n", .{op});
            var n: usize = 0;
            for (m.args) |*a| {
                if (untypedNewId(a)) {
                    try w.print("                const a{d} = try r.string();\n                const a{d} = try r.word();\n                const a{d} = try r.nonZero();\n", .{ n, n + 1, n + 2 });
                    n += 3;
                } else {
                    try w.print("                const a{d} = {s};\n", .{ n, try e.readExpr(i, a) });
                    n += 1;
                }
            }
            try w.writeAll("                try r.end();\n");
            if (m.args.len == 0) {
                try w.print("                return .{f};\n", .{std.zig.fmtIdP(m.name)});
            } else {
                try w.print("                return .{{ .{f} = .{{", .{std.zig.fmtIdP(m.name)});
                n = 0;
                for (m.args, 0..) |*a, idx| {
                    const sep = if (idx == 0) "" else ",";
                    if (untypedNewId(a)) {
                        try w.print("{s} .interface = a{d}, .interface_version = a{d}, .{f} = a{d}", .{ sep, n, n + 1, std.zig.fmtIdP(a.name), n + 2 });
                        n += 3;
                    } else {
                        try w.print("{s} .{f} = a{d}", .{ sep, std.zig.fmtIdP(a.name), n });
                        n += 1;
                    }
                }
                try w.writeAll(" } };\n");
            }
            try w.writeAll("            },\n");
        }
        try w.writeAll("            else => return error.Protocol,\n        }\n    }\n");
    }
};

fn putTaken(gpa: std.mem.Allocator, set: *std.StringHashMapUnmanaged(void), name: []const u8) !void {
    const gop = try set.getOrPut(gpa, name);
    if (!gop.found_existing) gop.key_ptr.* = try gpa.dupe(u8, name);
}

fn putTakenOwned(gpa: std.mem.Allocator, set: *std.StringHashMapUnmanaged(void), owned: []u8) !void {
    defer gpa.free(owned);
    try putTaken(gpa, set, owned);
}

/// Formats a tuple literal body as zig fmt does: `{}`, `{a}`, `{ a, b }`.
const Tuple = struct {
    items: []const []const u8,

    pub fn format(self: Tuple, w: *std.Io.Writer) std.Io.Writer.Error!void {
        switch (self.items.len) {
            0 => try w.writeAll("{}"),
            1 => try w.print("{{{s}}}", .{self.items[0]}),
            else => {
                try w.writeAll("{ ");
                for (self.items, 0..) |it, i| try w.print("{s}{s}", .{ if (i == 0) "" else ", ", it });
                try w.writeAll(" }");
            },
        }
    }
};

fn tuple(items: []const []const u8) Tuple {
    return .{ .items = items };
}

/// Formats text on one line, with runs of whitespace collapsed.
const OneLine = struct {
    s: []const u8,

    pub fn format(self: OneLine, w: *std.Io.Writer) std.Io.Writer.Error!void {
        var it = std.mem.tokenizeAny(u8, self.s, " \t\r\n");
        var first = true;
        while (it.next()) |word| {
            if (!first) try w.writeByte(' ');
            try w.writeAll(word);
            first = false;
        }
    }
};

fn oneLine(s: []const u8) OneLine {
    return .{ .s = s };
}

/// `set_title` -> `setTitle`.
pub fn camel(gpa: std.mem.Allocator, name: []const u8) ![]u8 {
    var out: std.ArrayList(u8) = .empty;
    var up = false;
    for (name) |c| {
        if (c == '_') {
            up = out.items.len > 0;
            continue;
        }
        try out.append(gpa, if (up) std.ascii.toUpper(c) else c);
        up = false;
    }
    return out.toOwnedSlice(gpa);
}

/// `dnd_action` -> `DndAction`.
pub fn pascal(gpa: std.mem.Allocator, name: []const u8) ![]u8 {
    const c = try camel(gpa, name);
    if (c.len > 0) c[0] = std.ascii.toUpper(c[0]);
    return c;
}

const prelude =
    \\const std = @import("std");
    \\
    \\/// A signed 24.8 fixed-point number.
    \\pub const Fixed = enum(i32) {
    \\    _,
    \\
    \\    /// The value as f64.
    \\    pub fn toF64(f: Fixed) f64 {
    \\        return @as(f64, @floatFromInt(@intFromEnum(f))) / 256.0;
    \\    }
    \\
    \\    /// The nearest fixed-point value to `v`, saturated.
    \\    pub fn fromF64(v: f64) Fixed {
    \\        const scaled = @round(v * 256.0);
    \\        const clamped = std.math.clamp(scaled, @as(f64, std.math.minInt(i32)), @as(f64, std.math.maxInt(i32)));
    \\        return @enumFromInt(@as(i32, @intFromFloat(clamped)));
    \\    }
    \\
    \\    /// An integer as fixed-point.
    \\    pub fn fromInt(v: i32) Fixed {
    \\        return @enumFromInt(v *% 256);
    \\    }
    \\};
    \\
    \\/// A message body that does not match its signature.
    \\pub const DecodeError = error{Protocol};
    \\
    \\/// Reads arguments from a message body.
    \\pub const Reader = struct {
    \\    body: []const u32,
    \\    pos: usize = 0,
    \\
    \\    /// The next word.
    \\    pub fn word(r: *Reader) DecodeError!u32 {
    \\        if (r.pos >= r.body.len) return error.Protocol;
    \\        defer r.pos += 1;
    \\        return r.body[r.pos];
    \\    }
    \\
    \\    /// The next word, which must not be zero.
    \\    pub fn nonZero(r: *Reader) DecodeError!u32 {
    \\        const v = try r.word();
    \\        return if (v == 0) error.Protocol else v;
