const std = @import("std");
const zg_build = @import("zg_build");

pub fn build(b: *std.Build) void {
    const f = zg_build.flags(b);
    const core = b.dependency("zg_core", f.args()).module("zg_core");
    const mod = zg_build.addPackage(b, f, .{
        .name = "zg_terminal",
        .imports = &.{.{ .name = "zg_core", .module = core }},
        .bench = "bench/main.zig",
    });
    const strict = b.option(bool, "terminal_conformance_strict", "Fail when a conformance category is under its minimum") orelse false;
    mod.addImport("zg_conformance", conformanceModule(b, strict));

    // zg_terminal_view: the GUI widget (E06.F04/F05) over zg_gui, a module
    // of its own so the headless core above never imports a GUI package.
    const view = b.addModule("zg_terminal_view", .{
        .root_source_file = b.path("src/view/root.zig"),
        .target = f.target,
        .imports = &.{
            .{ .name = "zg_core", .module = core },
            .{ .name = "zg_terminal", .module = mod },
            .{ .name = "zg_gui", .module = b.dependency("zg_gui", f.args()).module("zg_gui") },
            .{ .name = "zg_platform", .module = b.dependency("zg_platform", f.args()).module("zg_platform") },
        },
    });
    view.addImport("zg_options", zg_build.optionsModule(b, f));
    const view_tests = b.addRunArtifact(b.addTest(.{ .name = "zg_terminal_view", .root_module = zg_build.testModule(b, f, view) }));
    view_tests.skip_foreign_checks = true;
    b.step("test-view", "Run the zg_terminal_view tests").dependOn(&view_tests.step);
    b.top_level_steps.get("test").?.step.dependOn(&view_tests.step);

    // Reference-table generator (the root `docs-terminal-modes` step runs it).
    const docs_mod = b.createModule(.{
        .root_source_file = b.path("tools/gen_docs.zig"),
        .target = f.target,
        .optimize = .Debug,
    });
    docs_mod.addImport("zg_terminal", mod);
    b.installArtifact(b.addExecutable(.{ .name = "zg_terminal-docs", .root_module = docs_mod }));
}

/// Generates the `zg_conformance` module: every file under
/// `testdata/conformance/` as `files`, a list of `.{ path, bytes }` sorted by
/// path, plus `strict`. Files are copied next to the generated source so the
/// embeds stay inside the module's package.
fn conformanceModule(b: *std.Build, strict: bool) *std.Build.Module {
    const io = b.graph.io;
    const gpa = b.allocator;
    const wf = b.addWriteFiles();
    var src: std.ArrayList(u8) = .empty;
    src.print(gpa, "//! Generated by packages/terminal/build.zig: the conformance corpus.\npub const strict = {};\n", .{strict}) catch @panic("OOM");
    src.appendSlice(gpa, "pub const files: []const struct { []const u8, []const u8 } = &.{\n") catch @panic("OOM");
    var paths: std.ArrayList([]const u8) = .empty;
    if (b.build_root.handle.openDir(io, "testdata/conformance", .{ .iterate = true })) |d| {
        var dir = d;
        defer dir.close(io);
        var walker = dir.walk(gpa) catch @panic("OOM");
        defer walker.deinit();
        while (walker.next(io) catch @panic("cannot read testdata/conformance")) |entry| {
            if (entry.kind != .file) continue;
            const rel = b.dupe(entry.path);
            std.mem.replaceScalar(u8, rel, '\\', '/');
            paths.append(gpa, rel) catch @panic("OOM");
        }
    } else |_| {}
    std.mem.sort([]const u8, paths.items, {}, lessThan);
    for (paths.items) |rel| {
        const dst = b.fmt("conformance/{s}", .{rel});
        _ = wf.addCopyFile(b.path(b.fmt("testdata/conformance/{s}", .{rel})), dst);
        src.print(gpa, "    .{{ \"{f}\", @embedFile(\"{f}\") }},\n", .{ std.zig.fmtString(rel), std.zig.fmtString(dst) }) catch @panic("OOM");
    }
    src.appendSlice(gpa, "};\n") catch @panic("OOM");
    _ = wf.add("zg_conformance.zig", src.items);
    return b.createModule(.{ .root_source_file = wf.getDirectory().path(b, "zg_conformance.zig") });
}

fn lessThan(_: void, a: []const u8, c: []const u8) bool {
    return std.mem.lessThan(u8, a, c);
}
