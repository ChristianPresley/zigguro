//! spirvgen: generates `tools/spirv/spec.zig` from the vendored SPIR-V
//! grammar (E02.F05.S01.T01).
//!
//!   spirvgen <spirv.core.grammar.json> <extinst.glsl.std.450.grammar.json> <out.zig> [--check]
//!
//! With `--check`, nothing is written: the exit code is 1 when `<out.zig>`
//! differs from what would be generated (`zig build test` runs this).
//!
//! Mapping:
//! - every instruction becomes an `Opcode` tag (aliases become decls);
//! - a `ValueEnum` operand kind becomes a non-exhaustive `enum(u32)`;
//! - a `BitEnum` becomes a `packed struct(u32)` of bools;
//! - `operands(op)` and `enumParams(kind, value)` give the operand
//!   descriptors the validator and disassembler walk;
//! - `Decoration` and `ExecutionMode` also get a typed argument union
//!   (`DecorationArg`, `ExecutionModeArg`) for the builder.

const std = @import("std");

pub fn main(init: std.process.Init) !u8 {
    const arena = init.arena.allocator();
    const io = init.io;
    const args = try init.minimal.args.toSlice(arena);
    var positional: std.ArrayList([]const u8) = .empty;
    var check = false;
    for (args[1..]) |a| {
        if (std.mem.eql(u8, a, "--check")) check = true else try positional.append(arena, a);
    }
    if (positional.items.len != 3) {
        std.log.err("usage: spirvgen <core.json> <glsl.json> <out.zig> [--check]", .{});
        return 2;
    }
    const cwd = std.Io.Dir.cwd();
    const core = try cwd.readFileAlloc(io, positional.items[0], arena, .limited(16 << 20));
    const glsl = try cwd.readFileAlloc(io, positional.items[1], arena, .limited(1 << 20));
    const out = try generate(arena, core, glsl);
    const out_path = positional.items[2];
    if (check) {
        const current = cwd.readFileAlloc(io, out_path, arena, .limited(16 << 20)) catch |err| switch (err) {
            error.FileNotFound => "",
            else => return err,
        };
        if (!std.mem.eql(u8, current, out)) {
            std.log.err("{s} is out of date; run `zig build spirvgen`", .{out_path});
            return 1;
        }
        return 0;
    }
    try cwd.writeFile(io, .{ .sub_path = out_path, .data = out });
    return 0;
}

const Operand = struct {
    kind: []const u8,
    quantifier: ?[]const u8 = null,
    name: ?[]const u8 = null,
};

const Instruction = struct {
    opname: []const u8,
    opcode: u32,
    class: ?[]const u8 = null,
    operands: []const Operand = &.{},
    aliases: []const []const u8 = &.{},
};

const Enumerant = struct {
    enumerant: []const u8,
    value: std.json.Value,
    parameters: []const Operand = &.{},
    aliases: []const []const u8 = &.{},
};

const Kind = struct {
    category: []const u8,
    kind: []const u8,
    enumerants: []const Enumerant = &.{},
    bases: []const []const u8 = &.{},
};

const Core = struct {
    magic_number: []const u8,
    major_version: u32,
    minor_version: u32,
    revision: u32,
    instructions: []const Instruction,
    operand_kinds: []const Kind,
};

const ExtGrammar = struct {
    version: u32,
    revision: u32,
    instructions: []const Instruction,
};

pub const Error = error{ BadGrammar, OutOfMemory } || std.json.ParseError(std.json.Scanner) || std.Io.Writer.Error;

/// The generated source for the two grammar files. Deterministic.
pub fn generate(gpa: std.mem.Allocator, core_json: []const u8, glsl_json: []const u8) Error![]u8 {
    var arena_state: std.heap.ArenaAllocator = .init(gpa);
    defer arena_state.deinit();
    const arena = arena_state.allocator();
    const opts: std.json.ParseOptions = .{ .ignore_unknown_fields = true };
    const core = try std.json.parseFromSliceLeaky(Core, arena, core_json, opts);
    const glsl = try std.json.parseFromSliceLeaky(ExtGrammar, arena, glsl_json, opts);

    var out: std.Io.Writer.Allocating = .init(gpa);
    errdefer out.deinit();
    const w = &out.writer;
    try w.print(
        \\//! Generated by tools/spirv/grammar_gen.zig from the vendored SPIR-V
        \\//! grammar {d}.{d} revision {d} (tools/spirv/data/SOURCES.md). Do not edit;
        \\//! run `zig build spirvgen`.
        \\
        \\const std = @import("std");
        \\
        \\pub const magic: u32 = {s};
        \\pub const grammar_version: struct {{ major: u8, minor: u8 }} = .{{ .major = {d}, .minor = {d} }};
        \\
        \\
    , .{ core.major_version, core.minor_version, core.revision, core.magic_number, core.major_version, core.minor_version });

    try emitOpcodes(arena, w, core.instructions);
    for (core.operand_kinds) |k| {
        if (eql(k.category, "ValueEnum")) try emitValueEnum(arena, w, k) else if (eql(k.category, "BitEnum")) try emitBitEnum(arena, w, k);
    }
    try emitArgUnion(arena, w, core.operand_kinds, "Decoration");
    try emitArgUnion(arena, w, core.operand_kinds, "ExecutionMode");
    try emitGlsl(arena, w, glsl.instructions);
    try emitKinds(w, core.operand_kinds);
    try emitOperands(arena, w, core.instructions);
    try emitEnumParams(arena, w, core.operand_kinds);
    try emitNames(w, core.operand_kinds);
    return out.toOwnedSlice();
}

fn eql(a: []const u8, b: []const u8) bool {
    return std.mem.eql(u8, a, b);
}

fn id(name: []const u8) std.zig.FormatId {
    return std.zig.fmtId(name);
}

fn enumerantValue(e: Enumerant) Error!u32 {
    return switch (e.value) {
        .integer => |i| std.math.cast(u32, i) orelse error.BadGrammar,
        .string => |s| if (std.mem.startsWith(u8, s, "0x"))
            std.fmt.parseInt(u32, s[2..], 16) catch error.BadGrammar
        else
            std.fmt.parseInt(u32, s, 10) catch error.BadGrammar,
        else => error.BadGrammar,
    };
}

/// Instructions sorted by opcode, first name wins on a duplicate.
fn uniqueInstructions(arena: std.mem.Allocator, list: []const Instruction) Error![]Instruction {
    const sorted = try arena.dupe(Instruction, list);
    std.sort.block(Instruction, sorted, {}, struct {
        fn lt(_: void, a: Instruction, b: Instruction) bool {
            return a.opcode < b.opcode;
        }
    }.lt);
    var n: usize = 0;
    for (sorted) |ins| {
        if (n > 0 and sorted[n - 1].opcode == ins.opcode) continue;
        sorted[n] = ins;
        n += 1;
    }
    return sorted[0..n];
}

const Pair = struct { name: []const u8, value: u32, e: Enumerant };

/// Enumerants sorted by value, first name wins on a duplicate value.
fn uniqueEnumerants(arena: std.mem.Allocator, k: Kind) Error![]Pair {
    var list: std.ArrayList(Pair) = .empty;
    for (k.enumerants) |e| try list.append(arena, .{ .name = e.enumerant, .value = try enumerantValue(e), .e = e });
    std.sort.block(Pair, list.items, {}, struct {
        fn lt(_: void, a: Pair, b: Pair) bool {
            return a.value < b.value;
        }
    }.lt);
    var n: usize = 0;
    for (list.items) |p| {
        if (n > 0 and list.items[n - 1].value == p.value) continue;
        list.items[n] = p;
        n += 1;
    }
    return list.items[0..n];
}

fn emitOpcodes(arena: std.mem.Allocator, w: *std.Io.Writer, list: []const Instruction) Error!void {
    const ins = try uniqueInstructions(arena, list);
    try w.writeAll("pub const Opcode = enum(u16) {\n");
    for (ins) |i| try w.print("    {f} = {d},\n", .{ id(i.opname), i.opcode });
    try w.writeAll("    _,\n\n");
    for (ins) |i| for (i.aliases) |a| try w.print("    pub const {f}: Opcode = .{f};\n", .{ id(a), id(i.opname) });
    try w.writeAll("};\n\n");
}

fn emitValueEnum(arena: std.mem.Allocator, w: *std.Io.Writer, k: Kind) Error!void {
    const vals = try uniqueEnumerants(arena, k);
    try w.print("pub const {f} = enum(u32) {{\n", .{id(k.kind)});
    for (vals) |p| try w.print("    {f} = {d},\n", .{ id(p.name), p.value });
    try w.writeAll("    _,\n");
    var aliases = false;
    for (vals) |p| for (p.e.aliases) |a| {
        if (!aliases) try w.writeAll("\n");
        aliases = true;
        try w.print("    pub const {f}: {f} = .{f};\n", .{ id(a), id(k.kind), id(p.name) });
    };
    try w.writeAll("};\n\n");
}

fn emitBitEnum(arena: std.mem.Allocator, w: *std.Io.Writer, k: Kind) Error!void {
    const vals = try uniqueEnumerants(arena, k);
    var names: [32]?[]const u8 = @splat(null);
    for (vals) |p| {
        if (p.value == 0) continue;
        if (!std.math.isPowerOfTwo(p.value)) return error.BadGrammar;
        names[std.math.log2_int(u32, p.value)] = p.name;
    }
    try w.print("pub const {f} = packed struct(u32) {{\n", .{id(k.kind)});
    for (names, 0..) |n, bit| {
        if (n) |name| try w.print("    {f}: bool = false,\n", .{id(name)}) else try w.print("    _{d}: bool = false,\n", .{bit});
    }
    try w.writeAll("};\n\n");
}

/// The Zig type of one enumerant parameter in an argument union.
fn paramType(arena: std.mem.Allocator, kinds: []const Kind, o: Operand) Error![]const u8 {
    const base: []const u8 = blk: {
        if (eql(o.kind, "LiteralInteger") or eql(o.kind, "IdRef") or eql(o.kind, "IdScope") or eql(o.kind, "IdMemorySemantics")) break :blk "u32";
        if (eql(o.kind, "LiteralFloat")) break :blk "f32";
        if (eql(o.kind, "LiteralString")) break :blk "[]const u8";
        for (kinds) |k| if (eql(k.kind, o.kind) and (eql(k.category, "ValueEnum") or eql(k.category, "BitEnum"))) break :blk k.kind;
        return error.BadGrammar;
    };
    const q = o.quantifier orelse return base;
    if (eql(q, "?")) return std.fmt.allocPrint(arena, "?{s}", .{base});
    return std.fmt.allocPrint(arena, "[]const {s}", .{base});
}

fn emitArgUnion(arena: std.mem.Allocator, w: *std.Io.Writer, kinds: []const Kind, name: []const u8) Error!void {
    const k = for (kinds) |k| {
        if (eql(k.kind, name)) break k;
    } else return error.BadGrammar;
    const vals = try uniqueEnumerants(arena, k);
    try w.print("/// A `{s}` with its parameters, for the builder.\npub const {s}Arg = union(enum) {{\n", .{ name, name });
    for (vals) |p| {
        const params = p.e.parameters;
        if (params.len == 0) {
            try w.print("    {f},\n", .{id(p.name)});
        } else if (params.len == 1) {
            try w.print("    {f}: {s},\n", .{ id(p.name), try paramType(arena, kinds, params[0]) });
        } else {
            try w.print("    {f}: struct {{ ", .{id(p.name)});
            for (params, 0..) |o, i| try w.print("{s}{s}", .{ if (i > 0) ", " else "", try paramType(arena, kinds, o) });
            try w.writeAll(" },\n");
        }
    }
    try w.print(
        \\
        \\    pub fn tag(self: {s}Arg) {s} {{
        \\        return switch (self) {{
        \\            inline else => |_, t| @field({s}, @tagName(t)),
        \\        }};
        \\    }}
        \\}};
        \\
        \\
    , .{ name, name, name });
}

fn emitGlsl(arena: std.mem.Allocator, w: *std.Io.Writer, list: []const Instruction) Error!void {
    const ins = try uniqueInstructions(arena, list);
    try w.writeAll("/// GLSL.std.450 extended instructions (operands are all ids).\npub const GlslStd450 = enum(u32) {\n");
    for (ins) |i| try w.print("    {f} = {d},\n", .{ id(i.opname), i.opcode });
    try w.writeAll("    _,\n};\n\n");
}

fn emitKinds(w: *std.Io.Writer, kinds: []const Kind) Error!void {
    try w.writeAll(
        \\pub const Category = enum { id, literal, value_enum, bit_enum, composite };
        \\
        \\pub const OperandKind = enum(u8) {
        \\
    );
    for (kinds) |k| try w.print("    {f},\n", .{id(k.kind)});
    try w.writeAll(
        \\
        \\    pub fn category(k: OperandKind) Category {
        \\        return switch (k) {
        \\
    );
    for (kinds) |k| {
        const c = if (eql(k.category, "Id")) "id" else if (eql(k.category, "Literal")) "literal" else if (eql(k.category, "ValueEnum")) "value_enum" else if (eql(k.category, "BitEnum")) "bit_enum" else if (eql(k.category, "Composite")) "composite" else return error.BadGrammar;
        try w.print("            .{f} => .{s},\n", .{ id(k.kind), c });
    }
    try w.writeAll(
        \\        };
        \\    }
        \\
        \\    /// The two members of a `Pair*` composite kind.
        \\    pub fn bases(k: OperandKind) ?[2]OperandKind {
        \\        return switch (k) {
        \\
    );
    for (kinds) |k| if (eql(k.category, "Composite")) {
        if (k.bases.len != 2) return error.BadGrammar;
        try w.print("            .{f} => .{{ .{f}, .{f} }},\n", .{ id(k.kind), id(k.bases[0]), id(k.bases[1]) });
    };
    try w.writeAll(
        \\            else => null,
        \\        };
        \\    }
        \\};
        \\
        \\pub const Quantifier = enum(u2) { one, optional, variadic };
        \\pub const OperandDesc = struct { kind: OperandKind, quantifier: Quantifier = .one };
        \\
        \\
    );
}

/// `&.{ .{ .kind = .X }, ... }` as `zig fmt` lays it out.
fn writeDescs(w: *std.Io.Writer, ops: []const Operand) Error!void {
    const pad = if (ops.len > 1) " " else "";
    try w.print("&.{{{s}", .{pad});
    for (ops, 0..) |o, i| {
        if (i > 0) try w.writeAll(", ");
        try w.print(".{{ .kind = .{f}", .{id(o.kind)});
        if (o.quantifier) |q| try w.print(", .quantifier = .{s}", .{if (eql(q, "?")) "optional" else "variadic"});
        try w.writeAll(" }");
    }
    try w.print("{s}}}", .{pad});
}

fn emitOperands(arena: std.mem.Allocator, w: *std.Io.Writer, list: []const Instruction) Error!void {
    const ins = try uniqueInstructions(arena, list);
    try w.writeAll(
        \\/// The operand descriptors of `op` (empty for an unknown opcode).
        \\pub fn operands(op: Opcode) []const OperandDesc {
        \\    return switch (op) {
        \\
    );
    for (ins) |i| {
        try w.print("        .{f} => ", .{id(i.opname)});
        try writeDescs(w, i.operands);
        try w.writeAll(",\n");
    }
    try w.writeAll(
        \\        _ => &.{},
        \\    };
        \\}
        \\
        \\/// The instruction class from the grammar ("Type-Declaration", ...).
        \\pub fn class(op: Opcode) []const u8 {
        \\    return switch (op) {
        \\
    );
    for (ins) |i| try w.print("        .{f} => \"{s}\",\n", .{ id(i.opname), i.class orelse "" });
    try w.writeAll(
        \\        _ => "",
        \\    };
        \\}
        \\
        \\
    );
}

fn emitEnumParams(arena: std.mem.Allocator, w: *std.Io.Writer, kinds: []const Kind) Error!void {
    try w.writeAll(
        \\/// The extra operands that follow enumerant `value` of `kind` (for a
        \\/// bit enum, `value` is a single bit).
        \\pub fn enumParams(kind: OperandKind, value: u32) []const OperandDesc {
        \\    return switch (kind) {
        \\
    );
    for (kinds) |k| {
        if (!eql(k.category, "ValueEnum") and !eql(k.category, "BitEnum")) continue;
        const vals = try uniqueEnumerants(arena, k);
        var any = false;
        for (vals) |p| any = any or p.e.parameters.len > 0;
        if (!any) continue;
        try w.print("        .{f} => switch (value) {{\n", .{id(k.kind)});
        for (vals) |p| if (p.e.parameters.len > 0) {
            try w.print("            {d} => ", .{p.value});
            try writeDescs(w, p.e.parameters);
            try w.writeAll(",\n");
        };
        try w.writeAll("            else => &.{},\n        },\n");
    }
    try w.writeAll(
        \\        else => &.{},
        \\    };
        \\}
        \\
        \\
    );
}

fn emitNames(w: *std.Io.Writer, kinds: []const Kind) Error!void {
    try w.writeAll(
        \\/// The name of `value` in a value enum `kind`.
        \\pub fn valueName(kind: OperandKind, value: u32) ?[]const u8 {
        \\    return switch (kind) {
        \\
    );
    for (kinds) |k| if (eql(k.category, "ValueEnum"))
        try w.print("        .{f} => std.enums.tagName({f}, @enumFromInt(value)),\n", .{ id(k.kind), id(k.kind) });
    try w.writeAll(
        \\        else => null,
        \\    };
        \\}
        \\
        \\/// The name of `bit` in a bit enum `kind`.
        \\pub fn bitName(kind: OperandKind, bit: u5) ?[]const u8 {
        \\    return switch (kind) {
        \\
    );
    for (kinds) |k| if (eql(k.category, "BitEnum"))
        try w.print("        .{f} => fieldName({f}, bit),\n", .{ id(k.kind), id(k.kind) });
    try w.writeAll(
        \\        else => null,
        \\    };
        \\}
        \\
        \\fn fieldName(comptime T: type, bit: u5) ?[]const u8 {
        \\    switch (bit) {
        \\        inline else => |b| {
        \\            const name = @typeInfo(T).@"struct".fields[b].name;
        \\            return if (name[0] == '_') null else name;
        \\        },
        \\    }
        \\}
        \\
    );
}

test "grammar: deterministic output" {
    const gpa = std.testing.allocator;
    const core = @embedFile("data/spirv.core.grammar.json");
    const glsl = @embedFile("data/extinst.glsl.std.450.grammar.json");
    const one = try generate(gpa, core, glsl);
    defer gpa.free(one);
    const two = try generate(gpa, core, glsl);
    defer gpa.free(two);
    try std.testing.expectEqualStrings(one, two);
    try std.testing.expect(std.mem.indexOf(u8, one, "    OpTypeVoid = 19,\n") != null);
    try std.testing.expect(std.mem.indexOf(u8, one, "pub const Dim = enum(u32) {\n    @\"1D\" = 0,") != null);
}

