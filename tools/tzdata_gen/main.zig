//! tzdata-gen: builds the time-zone data zg_agents embeds for Windows,
//! which has no zoneinfo files (`zig build tzdata-gen`; E13.F02.S01.T04):
//!
//!   tools/tzdata_gen/data/windowsZones.xml (CLDR excerpt, territory 001)
//!   tools/tzdata_gen/data/links.txt        (tzdata.zi `L` lines)
//!   <zoneinfo>/<zone> TZif files           (an installed tzdata release)
//!     -> packages/agents/src/sched/tzdata/{zones.bin,windows_zones.zon}
//!
//! Every IANA zone the Windows zones map to is embedded, with its
//! version-1 data block dropped. `zones.bin` is little-endian: "ZGTZ",
//! u16 format (1), u16 count, u8 tzdata version length and the version,
//! then per zone (sorted by name) u8 name length, the name, u32 offset
//! and u32 length of its TZif bytes, then the TZif bytes. `--check`
//! compares instead of writing and exits 1 when the output is stale.
//! See docs/formats/timezones.md for the update procedure.

const std = @import("std");

const Allocator = std.mem.Allocator;
const Io = std.Io;

pub const out_dir = "packages/agents/src/sched/tzdata";

pub const MapRow = struct { windows: []const u8, iana: []const u8 };
pub const Link = struct { alias: []const u8, target: []const u8 };

/// `<mapZone other="W. Europe Standard Time" territory="001" type="Europe/Berlin"/>`.
pub fn parseMapZone(line: []const u8) ?MapRow {
    if (std.mem.indexOf(u8, line, "<mapZone ") == null) return null;
    if (std.mem.indexOf(u8, line, "territory=\"001\"") == null) return null;
    const other = attr(line, "other") orelse return null;
    const ty = attr(line, "type") orelse return null;
    // Territory 001 lists one zone; take the first if not.
    const first = std.mem.sliceTo(ty, ' ');
    return .{ .windows = other, .iana = first };
}

fn attr(line: []const u8, name: []const u8) ?[]const u8 {
    var buf: [32]u8 = undefined;
    const key = std.fmt.bufPrint(&buf, " {s}=\"", .{name}) catch return null;
    const i = std.mem.indexOf(u8, line, key) orelse return null;
    const s = line[i + key.len ..];
    const e = std.mem.indexOfScalar(u8, s, '"') orelse return null;
    return s[0..e];
}

/// `L Asia/Kolkata Asia/Calcutta`.
pub fn parseLink(line: []const u8) ?Link {
    var it = std.mem.tokenizeAny(u8, line, " \t\r");
    const l = it.next() orelse return null;
    if (!std.mem.eql(u8, l, "L")) return null;
    const target = it.next() orelse return null;
    const alias = it.next() orelse return null;
    return .{ .alias = alias, .target = target };
}

pub fn canonical(links: []const Link, name: []const u8) []const u8 {
    var n = name;
    var hops: u8 = 0;
    while (hops < 8) : (hops += 1) {
        for (links) |l| {
            if (std.mem.eql(u8, l.alias, n)) {
                n = l.target;
                break;
            }
        } else return n;
    }
    return n;
}

/// A TZif v2+ file with its version-1 block emptied (header kept, all
/// counts zero), which readers of version 2+ skip.
pub fn stripV1(gpa: Allocator, bytes: []const u8) ![]u8 {
    if (bytes.len < 44 or !std.mem.eql(u8, bytes[0..4], "TZif") or bytes[4] < '2') return error.NotTzifV2;
    var c: [6]u64 = undefined;
    for (&c, 0..) |*v, i| v.* = std.mem.readInt(u32, bytes[20 + i * 4 ..][0..4], .big);
    const v1_len = c[3] * 4 + c[3] + c[4] * 6 + c[5] + c[2] * 8 + c[1] + c[0];
    if (44 + v1_len > bytes.len) return error.NotTzifV2;
    const rest = bytes[@intCast(44 + v1_len)..];
    const out = try gpa.alloc(u8, 44 + rest.len);
    @memcpy(out[0..20], bytes[0..20]);
    @memset(out[20..44], 0);
    @memcpy(out[44..], rest);
    return out;
}

pub const Zone = struct { name: []const u8, data: []const u8 };

fn lessZone(_: void, a: Zone, b: Zone) bool {
    return std.mem.lessThan(u8, a.name, b.name);
}

fn lessRow(_: void, a: MapRow, b: MapRow) bool {
    return std.mem.lessThan(u8, a.windows, b.windows);
}

pub fn writeBin(w: *Io.Writer, version: []const u8, zones: []const Zone) !void {
    try w.writeAll("ZGTZ");
    try w.writeInt(u16, 1, .little);
    try w.writeInt(u16, @intCast(zones.len), .little);
    try w.writeByte(@intCast(version.len));
    try w.writeAll(version);
    var index_len: usize = 0;
    for (zones) |z| index_len += 1 + z.name.len + 8;
    var off: usize = 4 + 2 + 2 + 1 + version.len + index_len;
    for (zones) |z| {
        try w.writeByte(@intCast(z.name.len));
        try w.writeAll(z.name);
        try w.writeInt(u32, @intCast(off), .little);
        try w.writeInt(u32, @intCast(z.data.len), .little);
        off += z.data.len;
    }
    for (zones) |z| try w.writeAll(z.data);
}

pub fn writeZon(w: *Io.Writer, version: []const u8, cldr: []const u8, rows: []const MapRow, links: []const Link) !void {
    try w.writeAll("// Generated by tools/tzdata_gen (zig build tzdata-gen); do not edit.\n");
    try w.print(".{{\n    .tzdata = \"{s}\",\n    .cldr = \"{s}\",\n    // Windows zone id -> IANA zone (CLDR territory 001), sorted.\n    .map = .{{\n", .{ version, cldr });
    for (rows) |r| try w.print("        .{{ \"{s}\", \"{s}\" }},\n", .{ r.windows, r.iana });
    try w.writeAll("    },\n    // IANA alias -> zone.\n    .links = .{\n");
    for (links) |l| try w.print("        .{{ \"{s}\", \"{s}\" }},\n", .{ l.alias, l.target });
    try w.writeAll("    },\n}\n");
}

const Options = struct {
    root: []const u8 = ".",
    zoneinfo: []const u8 = "/usr/share/zoneinfo",
    check: bool = false,
};

pub fn main(init: std.process.Init) !u8 {
    const gpa = init.gpa;
    const io = init.io;
    var arena_state: std.heap.ArenaAllocator = .init(gpa);
    defer arena_state.deinit();
    const a = arena_state.allocator();
    var o: Options = .{};
    const args = try init.minimal.args.toSlice(a);
    var i: usize = 1;
    while (i < args.len) : (i += 1) {
        const arg = args[i];
        if (std.mem.eql(u8, arg, "--check")) {
            o.check = true;
        } else if (i + 1 < args.len and std.mem.eql(u8, arg, "--root")) {
            i += 1;
            o.root = args[i];
        } else if (i + 1 < args.len and std.mem.eql(u8, arg, "--zoneinfo")) {
            i += 1;
            o.zoneinfo = args[i];
        } else return usage();
    }
    var root = try Io.Dir.cwd().openDir(io, o.root, .{});
    defer root.close(io);
    var zi = try Io.Dir.cwd().openDir(io, o.zoneinfo, .{});
    defer zi.close(io);

    const xml = try root.readFileAlloc(io, "tools/tzdata_gen/data/windowsZones.xml", a, .limited(1 << 20));
    const link_text = try root.readFileAlloc(io, "tools/tzdata_gen/data/links.txt", a, .limited(1 << 20));
    const zi_head = try zi.readFileAlloc(io, "tzdata.zi", a, .limited(16 << 20));
    const version = blk: {
        const line = std.mem.sliceTo(zi_head, '\n');
        const p = "# version ";
        if (!std.mem.startsWith(u8, line, p)) return error.NoTzdataVersion;
        break :blk line[p.len..];
    };

    var links: std.ArrayList(Link) = .empty;
    var lines = std.mem.splitScalar(u8, link_text, '\n');
    while (lines.next()) |l| if (parseLink(l)) |k| try links.append(a, k);
    var cldr: []const u8 = "";
    var rows: std.ArrayList(MapRow) = .empty;
    lines = std.mem.splitScalar(u8, xml, '\n');
    while (lines.next()) |l| {
        if (std.mem.indexOf(u8, l, "<mapTimezones") != null) cldr = attr(l, "otherVersion") orelse "";
        if (parseMapZone(l)) |r| try rows.append(a, .{ .windows = r.windows, .iana = canonical(links.items, r.iana) });
    }
    std.mem.sort(MapRow, rows.items, {}, lessRow);

    var zones: std.ArrayList(Zone) = .empty;
    var seen: std.StringHashMapUnmanaged(void) = .empty;
    try seen.put(a, "UTC", {});
    try zones.append(a, .{ .name = "UTC", .data = try stripV1(a, try zi.readFileAlloc(io, "Etc/UTC", a, .limited(1 << 20))) });
    for (rows.items) |r| {
        if ((try seen.getOrPut(a, r.iana)).found_existing) continue;
        const bytes = zi.readFileAlloc(io, r.iana, a, .limited(1 << 20)) catch |e| {
            std.log.err("{s}: {t}", .{ r.iana, e });
            return 1;
        };
        try zones.append(a, .{ .name = r.iana, .data = try stripV1(a, bytes) });
    }
    std.mem.sort(Zone, zones.items, {}, lessZone);

    var bin: Io.Writer.Allocating = .init(a);
    try writeBin(&bin.writer, version, zones.items);
    var zon: Io.Writer.Allocating = .init(a);
    try writeZon(&zon.writer, version, cldr, rows.items, links.items);

    const outs = [_]struct { name: []const u8, data: []const u8 }{
        .{ .name = out_dir ++ "/zones.bin", .data = bin.written() },
        .{ .name = out_dir ++ "/windows_zones.zon", .data = zon.written() },
    };
    var stale = false;
    for (outs) |f| {
        if (o.check) {
            const cur = root.readFileAlloc(io, f.name, a, .limited(16 << 20)) catch "";
            if (!std.mem.eql(u8, cur, f.data)) {
                std.log.err("{s} is stale; run `zig build tzdata-gen`", .{f.name});
                stale = true;
            }
        } else {
            try root.writeFile(io, .{ .sub_path = f.name, .data = f.data });
        }
    }
    if (!o.check) std.log.info("tzdata {s}: {d} zones, {d} bytes; {d} Windows zones", .{ version, zones.items.len, bin.written().len, rows.items.len });
    return @intFromBool(stale);
}

fn usage() u8 {
    std.log.err("usage: tzdata-gen [--root <repo>] [--zoneinfo <dir>] [--check]", .{});
    return 2;
}

const testing = std.testing;

test "tzdata-gen: CLDR rows and links" {
    const r = parseMapZone("<mapZone other=\"W. Europe Standard Time\" territory=\"001\" type=\"Europe/Berlin\"/>").?;
    try testing.expectEqualStrings("W. Europe Standard Time", r.windows);
    try testing.expectEqualStrings("Europe/Berlin", r.iana);
    try testing.expect(parseMapZone("<mapZone other=\"X\" territory=\"DE\" type=\"Europe/Berlin Europe/Busingen\"/>") == null);
    const links = [_]Link{ parseLink("L Asia/Kolkata Asia/Calcutta").?, parseLink("L Europe/Kyiv Europe/Kiev").? };
    try testing.expectEqualStrings("Asia/Kolkata", canonical(&links, "Asia/Calcutta"));
    try testing.expectEqualStrings("Europe/Berlin", canonical(&links, "Europe/Berlin"));
    try testing.expect(parseLink("# comment") == null);
}

test "tzdata-gen: v1 block stripped and index written" {
    // A v2 file: v1 block with one type, then the v2 block and footer.
    var f: [44 + 6 + 4 + 44 + 6 + 4 + 5]u8 = @splat(0);
    @memcpy(f[0..5], "TZif2");
    std.mem.writeInt(u32, f[36..40], 1, .big); // typecnt
    std.mem.writeInt(u32, f[40..44], 4, .big); // charcnt
    @memcpy(f[50..54], "UTC\x00");
    @memcpy(f[54..59], "TZif2");
    std.mem.writeInt(u32, f[54 + 36 ..][0..4], 1, .big);
    std.mem.writeInt(u32, f[54 + 40 ..][0..4], 4, .big);
    @memcpy(f[104..108], "UTC\x00");
    @memcpy(f[108..113], "\nUTC0");
    const s = try stripV1(testing.allocator, &f);
    defer testing.allocator.free(s);
    try testing.expectEqual(f.len - 10, s.len);
    try testing.expectEqualSlices(u8, f[54..], s[44..]);
    var out: Io.Writer.Allocating = .init(testing.allocator);
    defer out.deinit();
    try writeBin(&out.writer, "2026e", &.{ .{ .name = "A", .data = "xy" }, .{ .name = "B", .data = "z" } });
    const b = out.written();
    try testing.expectEqualStrings("ZGTZ", b[0..4]);
    try testing.expectEqual(@as(u16, 2), std.mem.readInt(u16, b[6..8], .little));
    try testing.expectEqualStrings("xyz", b[b.len - 3 ..]);
}
