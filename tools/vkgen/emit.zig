//! Writes `vk.zig` from a resolved selection: constants, handles, enums,
//! packed-struct bitmasks, extern structs and unions with defaults, function
//! pointer types, the `Command` table and `Dispatch`, the `Result` error set,
//! extension info, `structExtends`, and compile-time C layout checks.
//! Output order follows vk.xml, so the file is deterministic.

const std = @import("std");
const registry = @import("registry.zig");
const resolve_mod = @import("resolve.zig");
const names = @import("names.zig");
const layout = @import("layout.zig");

const Registry = registry.Registry;
const Selection = resolve_mod.Selection;
const Decl = registry.Decl;
const CType = registry.CType;
const EnumValue = registry.EnumValue;

pub const Options = struct {
    /// Named in the header comment.
    source: []const u8 = "vk.xml",
    /// Re-export the hand-written helpers (`chain.zig`, `enumerate.zig`).
    helpers: bool = true,
    /// Emit the 64-bit C layout checks.
    layout_checks: bool = true,
};

pub const Error = error{ OutOfMemory, WriteFailed, UnknownType, NameCollision, UnknownLayout, UnknownCommandLevel };

/// Emits `vk.zig`. On error `culprit_out` names the offending item.
pub fn emit(a: std.mem.Allocator, reg: *const Registry, sel: *const Selection, w: *std.Io.Writer, opts: Options, culprit_out: ?*[]const u8) Error!void {
    var e: Emitter = .{ .reg = reg, .sel = sel, .a = a, .w = w, .opts = opts };
    e.run() catch |err| {
        if (culprit_out) |c| c.* = e.culprit;
        return err;
    };
}

/// File-scope snake_case names a parameter must not shadow.
const reserved_params = [_][]const u8{ "std", "builtin", "cc", "header_version", "check", "info" };

const Emitter = struct {
    reg: *const Registry,
    sel: *const Selection,
    a: std.mem.Allocator,
    w: *std.Io.Writer,
    opts: Options,
    culprit: []const u8 = "",
    /// Zig name of every emitted enum value, by Vulkan name.
    value_names: std.StringHashMapUnmanaged([]const u8) = .empty,
    /// FlagBits type → the bitmask type that carries its bits.
    flags_of: std.StringHashMapUnmanaged([]const u8) = .empty,
    /// API constant values (for layouts) and Zig names.
    const_values: std.StringHashMapUnmanaged(u64) = .empty,
    const_names: std.StringHashMapUnmanaged([]const u8) = .empty,
    /// Values not emitted (aliases that collide with another value's name).
    skipped: std.StringHashMapUnmanaged(void) = .empty,
    defaultable_memo: std.StringHashMapUnmanaged(bool) = .empty,

    fn fail(self: *Emitter, what: []const u8, err: Error) Error {
        self.culprit = what;
        return err;
    }

    fn print(self: *Emitter, comptime fmt: []const u8, args: anytype) Error!void {
        try self.w.print(fmt, args);
    }

    fn q(self: *Emitter, name: []const u8) Error![]const u8 {
        if (!names.needsQuote(name)) return name;
        return std.fmt.allocPrint(self.a, "@\"{s}\"", .{name});
    }

    fn run(self: *Emitter) Error!void {
        try self.prepare();
        try self.header();
        try self.constants();
        for (self.reg.types.keys()) |name| {
            if (!self.sel.hasType(name)) continue;
            try self.typeDecl(self.reg.types.get(name).?);
        }
        try self.results();
        try self.commands();
        try self.extensions();
        try self.extendsFn();
        if (self.opts.layout_checks) try self.layoutChecks();
        if (self.opts.helpers) {
            try self.print(
                \\
                \\/// Prepends `ext` to `base`'s pNext chain (checked with `structExtends`).
                \\pub const chain = @import("chain.zig").chain;
                \\/// The two-call enumerate idiom with `VK_INCOMPLETE` retry.
                \\pub const enumerateAlloc = @import("enumerate.zig").enumerateAlloc;
                \\
            , .{});
        }
    }

    fn prepare(self: *Emitter) Error!void {
        for (self.sel.types.keys()) |name| {
            const t = self.reg.types.get(name).?;
            if (t.category == .bitmask and t.alias == null) if (t.requires) |rq| try self.flags_of.put(self.a, rq, name);
        }
        if (self.reg.enums.get("API Constants")) |g| for (g.values.items) |v| {
            try self.const_names.put(self.a, v.name, try names.constName(self.a, v.name));
            if (constValue(v)) |n| try self.const_values.put(self.a, v.name, n);
        };
        // Name every value of every emitted group up front (sType defaults need them).
        for (self.sel.enum_values.keys(), self.sel.enum_values.values()) |group, list| {
            const vn = try self.valueNames(group, list.items);
            for (list.items, vn) |v, n| try self.value_names.put(self.a, v.name, n);
        }
    }

    fn header(self: *Emitter) Error!void {
        try self.print(
            \\//! Vulkan bindings generated by `tools/vkgen` from `{s}`
            \\//! (VK_HEADER_VERSION {d}); do not edit. Regenerate with `zig build vkgen`.
            \\//! Core 1.0 to {d}.{d} plus the extensions in `tools/vkgen/extensions.zon`.
            \\
            \\const std = @import("std");
            \\const builtin = @import("builtin");
            \\
            \\/// Vulkan's calling convention (stdcall on 32-bit Windows).
            \\pub const cc: std.builtin.CallingConvention = if (builtin.os.tag == .windows and builtin.cpu.arch == .x86) .{{ .x86_stdcall = .{{}} }} else .c;
            \\
            \\/// VK_HEADER_VERSION of the registry these bindings come from.
            \\pub const header_version = {d};
            \\
            \\/// `VK_MAKE_API_VERSION`.
            \\pub fn makeApiVersion(variant: u3, major: u7, minor: u10, patch: u12) u32 {{
            \\    return (@as(u32, variant) << 29) | (@as(u32, major) << 22) | (@as(u32, minor) << 12) | patch;
            \\}}
            \\
            \\/// A packed API version, as returned by `vkEnumerateInstanceVersion`.
            \\pub const Version = packed struct(u32) {{
            \\    patch: u12,
            \\    minor: u10,
            \\    major: u7,
            \\    variant: u3,
            \\
            \\    pub fn fromInt(v: u32) Version {{
            \\        return @bitCast(v);
            \\    }}
            \\    pub fn toInt(self: Version) u32 {{
            \\        return @bitCast(self);
            \\    }}
            \\    /// True if `self` is at least `major.minor`.
            \\    pub fn atLeast(self: Version, major: u7, minor: u10) bool {{
            \\        return self.major > major or (self.major == major and self.minor >= minor);
            \\    }}
            \\}};
            \\
            \\pub const api_version_1_0 = makeApiVersion(0, 1, 0, 0);
            \\pub const api_version_1_1 = makeApiVersion(0, 1, 1, 0);
            \\pub const api_version_1_2 = makeApiVersion(0, 1, 2, 0);
            \\pub const api_version_1_3 = makeApiVersion(0, 1, 3, 0);
            \\pub const api_version_1_4 = makeApiVersion(0, 1, 4, 0);
            \\
            \\
        , .{ self.opts.source, self.reg.header_version, maxVersion(self.sel) / 100, maxVersion(self.sel) % 100, self.reg.header_version });
    }

    fn constants(self: *Emitter) Error!void {
        const g = self.reg.enums.get("API Constants") orelse return;
        try self.print("// API constants.\n\n", .{});
        for (g.values.items) |v| {
            if (std.mem.eql(u8, v.name, "VK_TRUE") or std.mem.eql(u8, v.name, "VK_FALSE")) continue;
            const zn = self.const_names.get(v.name).?;
            switch (v.value) {
                .alias => |al| try self.print("pub const {s} = {s};\n", .{ zn, self.const_names.get(al) orelse return self.fail(al, error.UnknownType) }),
                .int => |n| try self.print("pub const {s}: {s} = {d};\n", .{ zn, try self.baseName(v.ctype orelse "uint32_t"), n }),
                .expr => |x| {
                    const ty = try self.baseName(v.ctype orelse "uint32_t");
                    if (constValue(v)) |n| {
                        try self.print("pub const {s}: {s} = 0x{x};\n", .{ zn, ty, n });
                    } else {
                        const f = std.mem.trimEnd(u8, x, "fF");
                        try self.print("pub const {s}: {s} = {s};\n", .{ zn, ty, f });
                    }
                },
                .bitpos => return self.fail(v.name, error.UnknownType),
            }
        }
        try self.print("\n", .{});
    }

    // ---- types -------------------------------------------------------------

    /// The Zig spelling of a C or Vulkan type name (by value).
    fn baseName(self: *Emitter, c: []const u8) Error![]const u8 {
        const prims = [_][2][]const u8{
            .{ "void", "void" },             .{ "char", "u8" },                 .{ "float", "f32" },
            .{ "double", "f64" },            .{ "uint8_t", "u8" },              .{ "uint16_t", "u16" },
            .{ "uint32_t", "u32" },          .{ "uint64_t", "u64" },            .{ "int8_t", "i8" },
            .{ "int16_t", "i16" },           .{ "int32_t", "i32" },             .{ "int64_t", "i64" },
            .{ "size_t", "usize" },          .{ "int", "c_int" },               .{ "DWORD", "u32" },
            .{ "HINSTANCE", "?*anyopaque" }, .{ "HWND", "?*anyopaque" },        .{ "HANDLE", "?*anyopaque" },
            .{ "HMONITOR", "?*anyopaque" },  .{ "LPCWSTR", "?[*:0]const u16" },
        };
        for (prims) |p| if (std.mem.eql(u8, p[0], c)) return p[1];
        if (std.mem.startsWith(u8, c, "Vk") or std.mem.startsWith(u8, c, "PFN_vk")) {
            if (!self.reg.types.contains(c)) return self.fail(c, error.UnknownType);
            return names.typeName(self.a, c);
        }
        return self.fail(c, error.UnknownType);
    }

    fn category(self: *Emitter, c: []const u8) ?registry.Category {
        const t = self.reg.resolveType(c) orelse return null;
        return t.category;
    }

    fn isFlags(self: *Emitter, c: []const u8) bool {
        const t = self.reg.resolveType(c) orelse return false;
        return t.category == .bitmask;
    }

    const Ctx = enum { member, param, fp_param, ret };

    /// The Zig type of a declaration.
    fn declType(self: *Emitter, d: Decl, ctx: Ctx, force_optional_ptr: bool) Error![]const u8 {
        var out: std.ArrayList(u8) = .empty;
        const t = d.ty;
        for (t.dims) |dim| switch (dim) {
            .lit => |n| try out.print(self.a, "[{d}]", .{n}),
            .constant => |cn| try out.print(self.a, "[{s}]", .{self.const_names.get(cn) orelse return self.fail(cn, error.UnknownType)}),
        };
        const is_void = std.mem.eql(u8, t.base, "void");
        if (t.ptr_depth == 0) {
            // Function pointers may be null as optional members and as
            // results (`vkGetInstanceProcAddr`).
            if (self.category(t.base) == .funcpointer and ((ctx == .member and d.isOptional(0)) or ctx == .ret)) try out.append(self.a, '?');
            try out.appendSlice(self.a, try self.baseName(t.base));
            return out.items;
        }
        var i: usize = 0;
        while (i < t.ptr_depth) : (i += 1) {
            const k = t.ptr_depth - 1 - i; // pointee index
            const void_level = k == 0 and is_void;
            const len: ?[]const u8 = if (ctx == .member or ctx == .param) d.lenAt(i) else null;
            const optional = void_level or switch (ctx) {
                .member => (i == 0 and (len != null or d.isOptional(0) or force_optional_ptr or std.mem.eql(u8, d.name, "pNext"))) or (i > 0 and d.isOptional(i)),
                .param => d.isOptional(i),
                .fp_param, .ret => false,
            };
            if (optional) try out.append(self.a, '?');
            const c_string = k == 0 and std.mem.eql(u8, t.base, "char");
            if (void_level) {
                try out.append(self.a, '*');
            } else if (len) |l| {
                try out.appendSlice(self.a, if (std.mem.eql(u8, l, "null-terminated")) "[*:0]" else "[*]");
            } else if (c_string) {
                try out.appendSlice(self.a, "[*:0]");
            } else try out.append(self.a, '*');
            if (t.pointee_const[k]) try out.appendSlice(self.a, "const ");
        }
        try out.appendSlice(self.a, if (is_void) "anyopaque" else try self.baseName(t.base));
        return out.items;
    }

    fn docLines(self: *Emitter, vk_name: []const u8) Error!void {
        try self.print("/// {s}\n", .{vk_name});
        if (self.sel.provided_by.get(vk_name)) |by| {
            try self.print("/// Provided by: ", .{});
            for (by.items, 0..) |b, i| try self.print("{s}{s}", .{ if (i > 0) ", " else "", b });
            try self.print("\n", .{});
        }
    }

    fn typeDecl(self: *Emitter, t: registry.Type) Error!void {
        switch (t.category) {
            .include, .define, .none, .group => return,
            else => {},
        }
        const zn = try names.typeName(self.a, t.name);
        if (t.alias) |al| {
            try self.print("/// {s} (alias)\npub const {s} = {s};\n\n", .{ t.name, zn, try names.typeName(self.a, al) });
            return;
        }
        switch (t.category) {
            .basetype => {
                if (std.mem.eql(u8, t.name, "VkBool32")) {
                    try self.print(
                        \\/// VkBool32
                        \\pub const Bool32 = enum(u32) {{
                        \\    @"false" = 0,
                        \\    @"true" = 1,
                        \\    _,
                        \\
                        \\    pub fn fromBool(b: bool) Bool32 {{
                        \\        return if (b) .@"true" else .@"false";
                        \\    }}
                        \\    pub fn toBool(self: Bool32) bool {{
                        \\        return self != .@"false";
                        \\    }}
                        \\}};
                        \\
                        \\
                    , .{});
                    return;
                }
                const b = t.base orelse return; // opaque platform types are never selected
                try self.docLines(t.name);
                const ptrs: []const u8 = if (b.ptr_depth > 0) "?*" else "";
                try self.print("pub const {s} = {s}{s};\n\n", .{ zn, ptrs, try self.baseName(b.base) });
            },
            .handle => {
                try self.docLines(t.name);
                try self.print("pub const {s} = enum({s}) {{ null_handle = 0, _ }};\n\n", .{ zn, if (t.dispatchable) "usize" else "u64" });
            },
            .@"enum" => {
                const g = self.reg.enums.get(t.name);
                if (g != null and g.?.kind == .bitmask) {
                    if (self.flags_of.get(t.name)) |flags| {
                        try self.print("/// {s}: the bits of `{s}`.\npub const {s} = {s};\n\n", .{ t.name, try names.typeName(self.a, flags), zn, try names.typeName(self.a, flags) });
                    } else {
                        try self.bitmask(t.name, zn, t.name, g.?.bitwidth);
                    }
                    return;
                }
                try self.enumType(t.name, zn);
            },
            .bitmask => {
                const width: u8 = if (t.base) |b| (if (std.mem.eql(u8, b.base, "VkFlags64")) 64 else 32) else 32;
                try self.bitmask(t.name, zn, t.requires, width);
            },
            .@"struct", .@"union" => try self.aggregate(t, zn),
            .funcpointer => {
                try self.docLines(t.name);
                try self.print("pub const {s} = *const fn (", .{zn});
                for (t.params, 0..) |p, i| {
                    try self.print("{s}{s}: {s}", .{ if (i > 0) ", " else "", try self.paramName(p.name), try self.declType(p, .fp_param, false) });
                }
                try self.print(") callconv(cc) {s};\n\n", .{try self.declType(.{ .name = "", .ty = t.ret.? }, .ret, false)});
            },
            else => {},
        }
    }

    fn paramName(self: *Emitter, vk: []const u8) Error![]const u8 {
        const s = try names.snake(self.a, vk);
        for (reserved_params) |r| if (std.mem.eql(u8, r, s)) return std.mem.concat(self.a, u8, &.{ s, "_" });
        return self.q(s);
    }

    /// Zig names for a group's values; falls back to keeping vendor tags if
    /// stripping them collides. An alias whose name collides with another
    /// value (`DISPATCH_BASE` next to `DISPATCH_BASE_BIT`) is not emitted
    /// and takes the other value's name.
    fn valueNames(self: *Emitter, group: []const u8, values: []const EnumValue) Error![]const []const u8 {
        const tag = self.reg.tagSuffix(group);
        const prefix = try names.enumPrefix(self.a, group, tag);
        for ([_]bool{ true, false }) |strip| {
            const out = try self.a.alloc([]const u8, values.len);
            const skip = try self.a.alloc(bool, values.len);
            @memset(skip, false);
            var seen: std.StringHashMapUnmanaged(usize) = .empty;
            var ok = true;
            for (values, out, 0..) |v, *o, i| {
                o.* = try names.enumValueName(self.a, prefix, v.name, tag, strip);
                const gop = try seen.getOrPut(self.a, o.*);
                if (!gop.found_existing) {
                    gop.value_ptr.* = i;
                } else if (v.value == .alias) {
                    skip[i] = true;
                } else if (values[gop.value_ptr.*].value == .alias) {
                    skip[gop.value_ptr.*] = true;
                    gop.value_ptr.* = i;
                } else {
                    ok = false;
                    self.culprit = v.name;
                }
            }
            if (ok) {
                for (values, skip) |v, sk| if (sk) try self.skipped.put(self.a, v.name, {});
                return out;
            }
        }
        return self.fail(self.culprit, error.NameCollision);
    }

    fn enumType(self: *Emitter, vk: []const u8, zn: []const u8) Error!void {
        const list = self.sel.enum_values.get(vk) orelse std.ArrayList(EnumValue).empty;
        try self.docLines(vk);
        try self.print("pub const {s} = enum(i32) {{\n", .{zn});
        var used: std.AutoHashMapUnmanaged(i64, []const u8) = .empty;
        var decls: std.ArrayList(u8) = .empty;
        for (list.items) |v| {
            if (self.skipped.contains(v.name)) continue;
            const n = try self.q(self.value_names.get(v.name).?);
            switch (v.value) {
                .int => |x| {
                    const gop = try used.getOrPut(self.a, x);
                    if (gop.found_existing) {
                        try decls.print(self.a, "    pub const {s}: {s} = .{s};\n", .{ n, zn, gop.value_ptr.* });
                    } else {
                        gop.value_ptr.* = n;
                        try self.print("    {s} = {d},\n", .{ n, x });
                    }
                },
                .alias => |al| try decls.print(self.a, "    pub const {s}: {s} = .{s};\n", .{ n, zn, try self.q(self.value_names.get(al) orelse return self.fail(al, error.UnknownType)) }),
                else => return self.fail(v.name, error.UnknownType),
            }
        }
        try self.print("    _,\n", .{});
        if (decls.items.len > 0) try self.print("\n{s}", .{decls.items});
        try self.print("}};\n\n", .{});
    }

    fn bitmask(self: *Emitter, vk: []const u8, zn: []const u8, bits_type: ?[]const u8, width: u8) Error!void {
        try self.docLines(vk);
        try self.print("pub const {s} = packed struct(u{d}) {{\n", .{ zn, width });
        var fields: [64]?[]const u8 = @splat(null);
        var decls: std.ArrayList(u8) = .empty;
        const list: []const EnumValue = if (bits_type) |bt| (if (self.sel.enum_values.get(bt)) |l| l.items else &.{}) else &.{};
        for (list) |v| {
            if (self.skipped.contains(v.name)) continue;
            const n = try self.q(self.value_names.get(v.name).?);
            switch (v.value) {
                .bitpos => |b| {
                    if (b >= width) return self.fail(v.name, error.UnknownType);
                    if (fields[b]) |first| {
                        try decls.print(self.a, "    pub const {s}: {s} = .{{ .{s} = true }};\n", .{ n, zn, first });
                    } else fields[b] = n;
                },
                .int => |x| {
                    const u: u64 = @bitCast(x);
                    if (u != 0 and std.math.isPowerOfTwo(u) and fields[std.math.log2_int(u64, u)] == null and std.math.log2_int(u64, u) < width) {
                        fields[std.math.log2_int(u64, u)] = n;
                    } else {
                        try decls.print(self.a, "    pub const {s}: {s} = .fromInt(0x{x});\n", .{ n, zn, u });
                    }
                },
                .alias => {},
                .expr => return self.fail(v.name, error.UnknownType),
            }
        }
        // Aliases name either a bit (a field) or a decl.
        for (list) |v| {
            if (self.skipped.contains(v.name)) continue;
            const al = switch (v.value) {
                .alias => |x| x,
                else => continue,
            };
            const n = try self.q(self.value_names.get(v.name).?);
            const target = try self.q(self.value_names.get(al) orelse return self.fail(al, error.UnknownType));
            const is_field = for (fields) |f| {
                if (f != null and std.mem.eql(u8, f.?, target)) break true;
            } else false;
            if (is_field) {
                try decls.print(self.a, "    pub const {s}: {s} = .{{ .{s} = true }};\n", .{ n, zn, target });
            } else {
                try decls.print(self.a, "    pub const {s}: {s} = {s}.{s};\n", .{ n, zn, zn, target });
            }
        }
        var b: usize = 0;
        while (b < width) {
            if (fields[b]) |f| {
                try self.print("    {s}: bool = false,\n", .{f});
                b += 1;
                continue;
            }
            var e = b;
            while (e < width and fields[e] == null) e += 1;
            try self.print("    _r{d}: u{d} = 0,\n", .{ b, e - b });
            b = e;
        }
        try self.print(
            \\
            \\{s}
            \\    pub inline fn toInt(self: {s}) u{d} {{
            \\        return @bitCast(self);
            \\    }}
            \\    pub inline fn fromInt(v: u{d}) {s} {{
            \\        return @bitCast(v);
            \\    }}
            \\    pub inline fn merge(lhs: {s}, rhs: {s}) {s} {{
            \\        return .fromInt(lhs.toInt() | rhs.toInt());
            \\    }}
            \\    pub inline fn intersect(lhs: {s}, rhs: {s}) {s} {{
            \\        return .fromInt(lhs.toInt() & rhs.toInt());
            \\    }}
            \\    pub inline fn contains(lhs: {s}, rhs: {s}) bool {{
            \\        return lhs.toInt() & rhs.toInt() == rhs.toInt();
            \\    }}
            \\    pub inline fn isEmpty(self: {s}) bool {{
            \\        return self.toInt() == 0;
            \\    }}
            \\}};
            \\
            \\
        , .{ decls.items, zn, width, width, zn, zn, zn, zn, zn, zn, zn, zn, zn, zn });
    }

    fn aggregate(self: *Emitter, t: registry.Type, zn: []const u8) Error!void {
        try self.docLines(t.name);
        const is_union = t.category == .@"union";
        try self.print("pub const {s} = extern {s} {{\n", .{ zn, if (is_union) "union" else "struct" });
        var seen: std.StringHashMapUnmanaged(void) = .empty;
        var i: usize = 0;
        while (i < t.members.len) {
            const m = t.members[i];
            if (m.ty.bitfield != null) {
                // Pack consecutive bit-fields into u32 units.
                var bits: u32 = 0;
                var j = i;
                var fname: std.ArrayList(u8) = .empty;
                var body: std.ArrayList(u8) = .empty;
                while (j < t.members.len) : (j += 1) {
                    const bw = t.members[j].ty.bitfield orelse break;
                    if (bits + bw > 32) break;
                    const sn = try names.snake(self.a, t.members[j].name);
                    if (fname.items.len > 0) try fname.append(self.a, '_');
                    try fname.appendSlice(self.a, sn);
                    try body.print(self.a, " {s}: u{d} = 0,", .{ try self.q(sn), bw });
                    bits += bw;
                }
                if (bits < 32) try body.print(self.a, " _pad: u{d} = 0,", .{32 - bits});
                try self.print("    {s}: packed struct(u32) {{{s} }}{s},\n", .{ try self.q(fname.items), body.items, if (is_union) "" else " = .{}" });
                i = j;
                continue;
            }
            const fname = try self.q(try names.snake(self.a, m.name));
            if ((try seen.getOrPut(self.a, fname)).found_existing) return self.fail(m.name, error.NameCollision);
            const ty = try self.declType(m, .member, t.returnedonly);
            try self.print("    {s}: {s}{s},\n", .{ fname, ty, try self.defaultFor(t, m, ty) });
            i += 1;
        }
        // structextends, restricted to selected types.
        var ext: std.ArrayList(u8) = .empty;
        for (t.structextends) |base| {
            if (!self.sel.hasType(base)) continue;
            try ext.print(self.a, "{s}{s}", .{ if (ext.items.len > 0) ", " else "", try names.typeName(self.a, base) });
        }
        if (ext.items.len > 0) try self.print("\n    pub const extends_structs = [_]type{{ {s} }};\n", .{ext.items});
        try self.print("}};\n\n", .{});
    }

    fn defaultFor(self: *Emitter, t: registry.Type, m: Decl, ty: []const u8) Error![]const u8 {
        if (t.category == .@"union") return "";
        if (m.values) |v| {
            if (std.mem.eql(u8, m.name, "sType")) return std.fmt.allocPrint(self.a, " = .{s}", .{try self.q(self.value_names.get(v) orelse return self.fail(v, error.UnknownType))});
        }
        if (ty.len > 0 and ty[0] == '?') return " = null";
        if (m.ty.dims.len == 0 and m.ty.ptr_depth == 0 and self.isFlags(m.ty.base)) return " = .{}";
        if (t.returnedonly) return std.fmt.allocPrint(self.a, " = std.mem.zeroes({s})", .{ty});
        const by_value = m.ty.dims.len == 0 and m.ty.ptr_depth == 0;
        if (by_value and std.mem.eql(u8, m.ty.base, "VkBool32")) return " = .@\"false\"";
        if (by_value and self.category(m.ty.base) == .@"struct" and try self.defaultable(m.ty.base)) return " = .{}";
        if (m.isOptional(0) and by_value) {
            const base = m.ty.base;
            if (layout.primitive(base) != null and !std.mem.startsWith(u8, ty, "?")) return " = 0";
            if (self.category(base)) |c| switch (c) {
                .handle => return " = .null_handle",
                .@"enum" => {
                    const g = self.reg.enums.get((self.reg.resolveType(base) orelse return "").name);
                    return if (g != null and g.?.kind == .bitmask) " = .{}" else " = @enumFromInt(0)";
                },
                .basetype => return " = 0",
                else => {},
            };
        }
        return "";
    }

    /// True if every member of struct `name` has a default, so `.{}` works.
    fn defaultable(self: *Emitter, name: []const u8) Error!bool {
        const t = self.reg.resolveType(name) orelse return false;
        if (t.category != .@"struct") return false;
        if (self.defaultable_memo.get(t.name)) |v| return v;
        try self.defaultable_memo.put(self.a, t.name, false); // no recursion through by-value cycles
        var ok = true;
        for (t.members) |m| {
            if (m.ty.bitfield != null) continue;
            const ty = try self.declType(m, .member, t.returnedonly);
            if ((try self.defaultFor(t.*, m, ty)).len == 0) {
                ok = false;
                break;
            }
        }
        try self.defaultable_memo.put(self.a, t.name, ok);
        return ok;
    }

    // ---- results, commands, extensions ------------------------------------

    fn results(self: *Emitter) Error!void {
        const list = self.sel.enum_values.get("VkResult") orelse return;
        var errs: std.ArrayList(struct { value: []const u8, err: []const u8 }) = .empty;
        for (list.items) |v| {
            if (v.value != .int or v.value.int >= 0) continue;
            try errs.append(self.a, .{ .value = self.value_names.get(v.name).?, .err = try names.errorName(self.a, v.name, self.reg.tags.items) });
        }
        try self.print("/// Every negative `Result`, plus `Unknown` for codes this file does not name.\npub const Error = error{{\n", .{});
        var has_unknown = false;
        for (errs.items) |e| {
            if (std.mem.eql(u8, e.err, "Unknown")) has_unknown = true;
            try self.print("    {s},\n", .{e.err});
        }
        if (!has_unknown) try self.print("    Unknown,\n", .{});
        try self.print(
            \\}};
            \\
            \\/// Maps negative results to `Error`; returns the others (`success`,
            \\/// `incomplete`, `suboptimal_khr`, `timeout`, `not_ready`, ...).
            \\pub fn check(r: Result) Error!Result {{
            \\    return switch (r) {{
            \\
        , .{});
        for (errs.items) |e| try self.print("        .{s} => error.{s},\n", .{ try self.q(e.value), e.err });
        try self.print(
            \\        else => if (@intFromEnum(r) < 0) error.Unknown else r,
            \\    }};
            \\}}
            \\
            \\/// The name of a result, for logs.
            \\pub fn resultName(r: Result) []const u8 {{
            \\    return std.enums.tagName(Result, r) orelse "unknown";
            \\}}
            \\
            \\
        , .{});
    }

    fn commandLevel(self: *Emitter, c: registry.Command) Error![]const u8 {
        const globals = [_][]const u8{ "vkCreateInstance", "vkGetInstanceProcAddr", "vkEnumerateInstanceVersion", "vkEnumerateInstanceExtensionProperties", "vkEnumerateInstanceLayerProperties" };
        for (globals) |g| if (std.mem.eql(u8, g, c.name)) return "global";
        if (c.params.len == 0) return self.fail(c.name, error.UnknownCommandLevel);
        const first = c.params[0].ty.base;
        if (std.mem.eql(u8, first, "VkInstance") or std.mem.eql(u8, first, "VkPhysicalDevice")) return "instance";
        if (std.mem.eql(u8, first, "VkDevice") or std.mem.eql(u8, first, "VkQueue") or std.mem.eql(u8, first, "VkCommandBuffer")) return "device";
        return self.fail(c.name, error.UnknownCommandLevel);
    }

    fn commands(self: *Emitter) Error!void {
        // Aliases by target.
        var aliases: std.StringHashMapUnmanaged(std.ArrayList([]const u8)) = .empty;
        for (self.reg.commands.values()) |c| {
            const al = c.alias orelse continue;
            const target = (self.reg.resolveCommand(al) orelse continue).name;
            const gop = try aliases.getOrPut(self.a, target);
            if (!gop.found_existing) gop.value_ptr.* = .empty;
            try gop.value_ptr.append(self.a, c.name);
        }
        // Commands in registry order.
        var cmds: std.ArrayList(registry.Command) = .empty;
        for (self.reg.commands.values()) |c| if (c.alias == null and self.sel.commands.contains(c.name)) try cmds.append(self.a, c);

        try self.print("// Commands.\n\n", .{});
        for (cmds.items) |c| {
            try self.docLines(c.name);
            try self.print("pub const {s} = *const fn (", .{try names.typeName(self.a, try std.mem.concat(self.a, u8, &.{ "PFN_", c.name }))});
            for (c.params, 0..) |p, i| try self.print("{s}{s}: {s}", .{ if (i > 0) ", " else "", try self.paramName(p.name), try self.declType(p, .param, false) });
            try self.print(") callconv(cc) {s};\n\n", .{try self.declType(.{ .name = "", .ty = c.ret }, .ret, false)});
        }
        try self.print(
            \\/// Which table a command is loaded into.
            \\pub const Level = enum {{ global, instance, device }};
            \\
            \\/// Who provides a command: a core version (major * 100 + minor) or an extension.
            \\pub const Provider = union(enum) {{ version: u32, extension: Extension }};
            \\
            \\/// Static facts about a command.
            \\pub const CommandInfo = struct {{
            \\    name: [:0]const u8,
            \\    level: Level,
            \\    /// Names it may be loaded by when the core name is missing (promoted commands).
            \\    aliases: []const [:0]const u8,
            \\    Pfn: type,
            \\    provided_by: []const Provider,
            \\}};
            \\
            \\/// Every selected command.
            \\pub const Command = enum {{
            \\
        , .{});
        for (cmds.items) |c| try self.print("    {s},\n", .{try self.q(try names.commandName(self.a, c.name))});
        try self.print("}};\n\nconst command_info = [_]CommandInfo{{\n", .{});
        for (cmds.items) |c| {
            try self.print("    .{{ .name = \"{s}\", .level = .{s}, .aliases = &.{{", .{ c.name, try self.commandLevel(c) });
            if (aliases.get(c.name)) |al| for (al.items, 0..) |n, i| try self.print("{s}\"{s}\"", .{ if (i > 0) ", " else " ", n });
            try self.print(" }}, .Pfn = {s}, .provided_by = &.{{", .{try names.typeName(self.a, try std.mem.concat(self.a, u8, &.{ "PFN_", c.name }))});
            if (self.sel.provided_by.get(c.name)) |by| for (by.items, 0..) |b, i| {
                try self.print("{s}{s}", .{ if (i > 0) ", " else " ", try self.provider(b) });
            };
            try self.print(" }} }},\n", .{});
        }
        try self.print(
            \\}};
            \\
            \\/// Static facts about `c`.
            \\pub fn info(comptime c: Command) CommandInfo {{
            \\    return command_info[@intFromEnum(c)];
            \\}}
            \\
            \\/// The function pointer type of `c`.
            \\pub fn PfnOf(comptime c: Command) type {{
            \\    return info(c).Pfn;
            \\}}
            \\
            \\/// `vkXxx`.
            \\pub fn commandName(comptime c: Command) [:0]const u8 {{
            \\    return info(c).name;
            \\}}
            \\
            \\pub fn commandLevel(comptime c: Command) Level {{
            \\    return info(c).level;
            \\}}
            \\
            \\pub fn commandAliases(comptime c: Command) []const [:0]const u8 {{
            \\    return info(c).aliases;
            \\}}
            \\
            \\/// A dispatch table with exactly the listed commands, one field per
            \\/// command named like `Command` (`table.create_image(...)`). Global
            \\/// tables may hold only global commands.
            \\pub fn Dispatch(comptime level: Level, comptime cmds: []const Command) type {{
            \\    var field_names: [cmds.len][]const u8 = undefined;
            \\    var field_types: [cmds.len]type = undefined;
            \\    for (cmds, 0..) |c, i| {{
            \\        if (level == .global and info(c).level != .global) @compileError(@tagName(c) ++ " is not a global command");
            \\        if (level == .instance and info(c).level == .global and c != .get_instance_proc_addr) @compileError(@tagName(c) ++ " is a global command");
            \\        field_names[i] = @tagName(c);
            \\        field_types[i] = info(c).Pfn;
            \\    }}
            \\    return @Struct(.auto, null, &field_names, &field_types, &@splat(.{{}}));
            \\}}
            \\
            \\
        , .{});
    }

    fn provider(self: *Emitter, by: []const u8) Error![]const u8 {
        for (self.sel.features.items) |f| if (std.mem.eql(u8, f.name, by)) return std.fmt.allocPrint(self.a, ".{{ .version = {d} }}", .{f.number});
        return std.fmt.allocPrint(self.a, ".{{ .extension = .{s} }}", .{try names.extensionName(self.a, by)});
    }

    fn extensions(self: *Emitter) Error!void {
        try self.print(
            \\/// Static facts about an extension.
            \\pub const ExtensionInfo = struct {{
            \\    name: [:0]const u8,
            \\    number: u32,
            \\    spec_version: u32,
            \\    kind: enum {{ instance, device }},
            \\    /// Core version (major * 100 + minor) it was promoted to, or 0.
            \\    promoted_to: u32,
            \\}};
            \\
            \\/// Every selected extension.
            \\pub const Extension = enum {{
            \\
        , .{});
        for (self.sel.extensions.items) |e| try self.print("    {s},\n", .{try names.extensionName(self.a, e.iface.name)});
        try self.print("}};\n\nconst extension_info = [_]ExtensionInfo{{\n", .{});
        for (self.sel.extensions.items) |e| {
            var promoted: u32 = 0;
            if (e.iface.promotedto) |pt| for (self.reg.features.items) |f| {
                if (std.mem.eql(u8, f.name, pt)) promoted = f.number;
            };
            try self.print("    .{{ .name = \"{s}\", .number = {d}, .spec_version = {d}, .kind = .{s}, .promoted_to = {d} }},\n", .{ e.iface.name, e.iface.number, e.spec_version, e.iface.ext_type orelse "device", promoted });
        }
        try self.print(
            \\}};
            \\
            \\/// Static facts about `e`.
            \\pub fn extensionInfo(e: Extension) ExtensionInfo {{
            \\    return extension_info[@intFromEnum(e)];
            \\}}
            \\
            \\/// The extension named `name` (`VK_KHR_swapchain`), or null.
            \\pub fn extensionByName(name: []const u8) ?Extension {{
            \\    for (extension_info, 0..) |e, i| if (std.mem.eql(u8, e.name, name)) return @enumFromInt(i);
            \\    return null;
            \\}}
            \\
            \\
        , .{});
    }

    fn extendsFn(self: *Emitter) Error!void {
        try self.print(
            \\/// True if `Ext` may appear in the pNext chain of `Base` (vk.xml `structextends`).
            \\pub fn structExtends(comptime Ext: type, comptime Base: type) bool {{
            \\    if (!@hasDecl(Ext, "extends_structs")) return false;
            \\    inline for (Ext.extends_structs) |T| if (T == Base) return true;
            \\    return false;
            \\}}
            \\
        , .{});
    }

    fn layoutChecks(self: *Emitter) Error!void {
        var calc: layout.Calc = .{ .reg = self.reg, .a = self.a, .constants = &self.const_values };
        try self.print(
            \\
            \\// C layouts on 64-bit targets, computed by vkgen from vk.xml.
            \\const c_layouts = .{{
            \\
        , .{});
        for (self.reg.types.keys()) |name| {
            if (!self.sel.hasType(name)) continue;
            const t = self.reg.types.get(name).?;
            if (t.alias != null or (t.category != .@"struct" and t.category != .@"union")) continue;
            const l = calc.of(name) catch return self.fail(calc.culprit, error.UnknownLayout);
            try self.print("    .{{ {s}, {d}, {d} }},\n", .{ try names.typeName(self.a, name), l.size, l.@"align" });
        }
        try self.print(
            \\}};
            \\
            \\comptime {{
            \\    if (@sizeOf(usize) == 8) {{
            \\        @setEvalBranchQuota(100_000);
            \\        for (c_layouts) |e| {{
            \\            if (@sizeOf(e[0]) != e[1] or @alignOf(e[0]) != e[2]) @compileError("C layout mismatch: " ++ @typeName(e[0]));
            \\        }}
            \\    }}
            \\}}
            \\
        , .{});
    }
};

fn maxVersion(sel: *const Selection) u32 {
    var m: u32 = 100;
    for (sel.features.items) |f| m = @max(m, f.number);
    return m;
}

/// The integer value of an API constant, if it has one.
fn constValue(v: EnumValue) ?u64 {
    switch (v.value) {
        .int => |n| return if (n >= 0) @intCast(n) else null,
        .expr => |x| {
            // (~0U), (~1U), (~2U), (~0ULL)
            if (!std.mem.startsWith(u8, x, "(~") or !std.mem.endsWith(u8, x, ")")) return null;
            const inner = x[2 .. x.len - 1];
            const is64 = std.mem.endsWith(u8, inner, "ULL");
            const digits = std.mem.trimEnd(u8, inner, "UL");
            const n = std.fmt.parseInt(u64, digits, 10) catch return null;
            return if (is64) ~n else @as(u64, ~@as(u32, @intCast(n)));
        },
        else => return null,
    }
}

test "emit: constValue" {
    try std.testing.expectEqual(@as(?u64, 0xffffffff), constValue(.{ .name = "", .value = .{ .expr = "(~0U)" } }));
    try std.testing.expectEqual(@as(?u64, 0xfffffffe), constValue(.{ .name = "", .value = .{ .expr = "(~1U)" } }));
    try std.testing.expectEqual(@as(?u64, std.math.maxInt(u64)), constValue(.{ .name = "", .value = .{ .expr = "(~0ULL)" } }));
    try std.testing.expectEqual(@as(?u64, null), constValue(.{ .name = "", .value = .{ .expr = "1000.0F" } }));
}
