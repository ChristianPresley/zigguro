//! ucd_enums: Unicode property enums shared by `ucdgen` and `zg_text`, plus
//! the packed per-code-point records the generated tables store.
//!
//! Enum field names are the UCD short aliases. The block between the
//! `ucdgen:enums` markers is produced by `ucdgen enums PropertyValueAliases.txt`
//! and checked against the vendored file every time the generator runs, so a
//! new property value in a future UCD fails with an error naming the enum to
//! extend. Regenerate it with `zig build enums -- <PropertyValueAliases.txt>`
//! in tools/ucdgen.

const std = @import("std");

/// The properties of one code point that the hot algorithms read
/// (segmentation, line breaking, bidi, width, itemization, normalization).
pub const Props = packed struct(u64) {
    gc: GeneralCategory = .Cn,
    gcb: GraphemeBreak = .XX,
    incb: IndicConjunctBreak = .None,
    ext_pict: bool = false,
    emoji: bool = false,
    emoji_pres: bool = false,
    emoji_mod: bool = false,
    emoji_mod_base: bool = false,
    wb: WordBreak = .XX,
    lb: LineBreak = .XX,
    bidi: BidiClass = .L,
    bidi_mirrored: bool = false,
    bpt: BracketType = .n,
    eaw: EastAsianWidth = .N,
    script: Script = .Zzzz,
    ccc: u8 = 0,
    jt: JoiningType = .U,
    nfc_qc: QuickCheck = .Y,
    _pad: u4 = 0,
};

/// Less frequently used per-code-point data, in a second table.
pub const Aux = packed struct(u32) {
    isc: IndicSyllabic = .Other,
    ipc: IndicPositional = .NA,
    /// Listed as a base in emoji-variation-sequences.txt.
    vs_base: bool = false,
    /// DerivedCoreProperties Cased.
    cased: bool = false,
    /// DerivedCoreProperties Case_Ignorable.
    case_ignorable: bool = false,
    /// Has a canonical or compatibility decomposition (Hangul excluded).
    has_decomp: bool = false,
    /// Has a simple or full case mapping that differs from itself.
    has_case_map: bool = false,
    /// Has a C, S or F case folding.
    has_fold: bool = false,
    /// DerivedNormalizationProps Full_Composition_Exclusion.
    full_comp_ex: bool = false,
    nfd_qc: QuickCheck = .Y,
    nfkd_qc: QuickCheck = .Y,
    nfkc_qc: QuickCheck = .Y,
    /// DerivedCoreProperties Default_Ignorable_Code_Point.
    default_ignorable: bool = false,
    /// PropList White_Space.
    white_space: bool = false,
    _pad: u6 = 0,
};

comptime {
    std.debug.assert(@bitSizeOf(Props) == 64 and @bitSizeOf(Aux) == 32);
}

