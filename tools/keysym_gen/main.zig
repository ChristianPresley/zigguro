//! keysym-gen: turns the vendored xorgproto headers into the keysym tables
//! used by the XKB parser (`zig build keysym-gen`):
//!
//!   packages/platform/data/{keysymdef.h,XF86keysym.h}
//!     -> packages/platform/src/xkb/keysym_data.zig
//!
//! It reads `#define XK_name 0xVALUE /* U+XXXX NAME */` lines (and the
//! `/*(U+XXXX ...)*/` legacy form), plus `XF86XK_name` with literal values
//! or `_EVDEVK(0x...)`. It emits a name table sorted for binary search, a
//! value table where the first non-deprecated name wins, and keysym to
//! Unicode for keysyms outside the direct mappings. `--check` compares
//! instead of writing and exits 1 when the checked-in file is stale.

const std = @import("std");

/// One parsed `#define`.
pub const Def = struct {
    name: []const u8,
    value: u32,
    /// The U+ code point from the comment, if any.
    cp: ?u21 = null,
    deprecated: bool = false,
};

const evdev_base: u32 = 0x10081000;

/// Parses one header line, or returns null for anything that is not a
/// keysym definition. `prefix` is "XK_" or "XF86XK_"; XF86 names keep
/// "XF86" in front, as xkbcommon spells them.
pub fn parseLine(line: []const u8, prefix: []const u8) ?Def {
    const head = "#define ";
    if (!std.mem.startsWith(u8, line, head)) return null;
    var rest = std.mem.trimStart(u8, line[head.len..], " \t");
    if (!std.mem.startsWith(u8, rest, prefix)) return null;
    const name_end = std.mem.indexOfAny(u8, rest, " \t") orelse return null;
    const raw_name = rest[prefix.len..name_end];
    if (raw_name.len == 0) return null;
    rest = std.mem.trimStart(u8, rest[name_end..], " \t");
    var value: u32 = undefined;
    if (std.mem.startsWith(u8, rest, "_EVDEVK(")) {
        const close = std.mem.indexOfScalar(u8, rest, ')') orelse return null;
        const v = parseNum(rest["_EVDEVK(".len..close]) orelse return null;
        value = evdev_base + v;
        rest = rest[close + 1 ..];
    } else {
        const end = std.mem.indexOfAny(u8, rest, " \t") orelse rest.len;
        value = parseNum(rest[0..end]) orelse return null;
        rest = rest[end..];
    }
    var d: Def = .{ .name = raw_name, .value = value };
    if (std.mem.indexOf(u8, rest, "/*")) |c| {
        const comment = rest[c + 2 ..];
        d.deprecated = std.mem.indexOf(u8, comment, "deprecated") != null;
        const t = std.mem.trimStart(u8, comment, " (");
        if (std.mem.startsWith(u8, t, "U+")) {
            var j: usize = 2;
            while (j < t.len and std.ascii.isHex(t[j])) j += 1;
            d.cp = std.fmt.parseInt(u21, t[2..j], 16) catch null;
        }
    }
    return d;
}

fn parseNum(s: []const u8) ?u32 {
    if (std.mem.startsWith(u8, s, "0x") or std.mem.startsWith(u8, s, "0X")) return std.fmt.parseInt(u32, s[2..], 16) catch null;
    return std.fmt.parseInt(u32, s, 10) catch null;
}

/// Whether `ks` maps to Unicode without a table: Latin-1 or 0x01000000+cp.
pub fn directUnicode(ks: u32, cp: u21) bool {
    if ((ks >= 0x20 and ks <= 0x7e) or (ks >= 0xa0 and ks <= 0xff)) return ks == cp;
    if (ks >= 0x01000100 and ks <= 0x0110ffff) return ks - 0x01000000 == cp;
    return false;
}

fn nameLess(_: void, a: Def, b: Def) bool {
    return std.mem.lessThan(u8, a.name, b.name);
}

/// Renders the generated Zig source from definitions in header order.
pub fn render(gpa: std.mem.Allocator, defs: []const Def, xf86_from: usize) ![]u8 {
    var out: std.Io.Writer.Allocating = .init(gpa);
    errdefer out.deinit();
    const w = &out.writer;
    try w.writeAll(
        \\//! Generated by tools/keysym_gen from packages/platform/data/keysymdef.h
        \\//! and XF86keysym.h. Do not edit; run `zig build keysym-gen`.
        \\
        \\/// A keysym name and value.
        \\pub const Entry = struct { name: []const u8, value: u32 };
        \\/// A keysym and its Unicode code point.
        \\pub const Unicode = struct { keysym: u32, cp: u21 };
        \\
        \\
    );

    // Names (XF86 ones get their prefix back), sorted by name.
    var named: std.ArrayList(Def) = .empty;
    defer named.deinit(gpa);
    for (defs, 0..) |d, i| {
        var e = d;
        if (i >= xf86_from) e.name = try std.fmt.allocPrint(gpa, "XF86{s}", .{d.name});
        try named.append(gpa, e);
    }
    const in_order = try gpa.dupe(Def, named.items);
    defer gpa.free(in_order);
    std.mem.sort(Def, named.items, {}, nameLess);
    try w.writeAll("/// Every keysym name, sorted by name for binary search.\npub const by_name = [_]Entry{\n");
    var prev: []const u8 = "";
    for (named.items) |d| {
        if (std.mem.eql(u8, d.name, prev)) continue;
        prev = d.name;
        try w.print("    .{{ .name = \"{s}\", .value = 0x{x} }},\n", .{ d.name, d.value });
    }
    try w.writeAll("};\n\n");

    // Value -> preferred name: first non-deprecated, else first.
    const Pick = struct { value: u32, name: []const u8, deprecated: bool };
    var picks: std.AutoArrayHashMapUnmanaged(u32, Pick) = .empty;
    defer picks.deinit(gpa);
    for (in_order) |d| {
        const gop = try picks.getOrPut(gpa, d.value);
        if (!gop.found_existing or (gop.value_ptr.deprecated and !d.deprecated)) {
            gop.value_ptr.* = .{ .value = d.value, .name = d.name, .deprecated = d.deprecated };
        }
    }
    const vals = try gpa.dupe(Pick, picks.values());
    defer gpa.free(vals);
    std.mem.sort(Pick, vals, {}, struct {
        fn lt(_: void, a: Pick, b: Pick) bool {
            return a.value < b.value;
        }
    }.lt);
    try w.writeAll("/// One preferred name per keysym value, sorted by value.\npub const by_value = [_]Entry{\n");
    for (vals) |p| try w.print("    .{{ .name = \"{s}\", .value = 0x{x} }},\n", .{ p.name, p.value });
    try w.writeAll("};\n\n");

    // Keysym -> Unicode outside the direct ranges; first definition wins.
    var uni: std.AutoArrayHashMapUnmanaged(u32, u21) = .empty;
    defer uni.deinit(gpa);
    for (in_order) |d| {
        const cp = d.cp orelse continue;
        if (directUnicode(d.value, cp)) continue;
        const gop = try uni.getOrPut(gpa, d.value);
        if (!gop.found_existing) gop.value_ptr.* = cp;
    }
    const ks = try gpa.dupe(u32, uni.keys());
    defer gpa.free(ks);
    std.mem.sort(u32, ks, {}, std.sort.asc(u32));
    try w.writeAll("/// Keysym to Unicode for keysyms not mapped directly, sorted by keysym.\npub const to_unicode = [_]Unicode{\n");
    for (ks) |k| try w.print("    .{{ .keysym = 0x{x}, .cp = 0x{x} }},\n", .{ k, uni.get(k).? });
    try w.writeAll("};\n");
    return out.toOwnedSlice();
}

/// Parses both headers into definitions (keysymdef first), returning the
/// index where the XF86 entries start.
pub fn parseHeaders(gpa: std.mem.Allocator, keysymdef: []const u8, xf86: []const u8, out: *std.ArrayList(Def)) !usize {
    var it = std.mem.splitScalar(u8, keysymdef, '\n');
    while (it.next()) |line| if (parseLine(line, "XK_")) |d| try out.append(gpa, d);
    const xf86_from = out.items.len;
    var it2 = std.mem.splitScalar(u8, xf86, '\n');
    while (it2.next()) |line| if (parseLine(line, "XF86XK_")) |d| try out.append(gpa, d);
    return xf86_from;
}

const out_path = "packages/platform/src/xkb/keysym_data.zig";

pub fn main(init: std.process.Init) !u8 {
    const gpa = init.arena.allocator();
    const io = init.io;
    const args = try init.minimal.args.toSlice(gpa);
    var root_path: []const u8 = ".";
    var check = false;
    var i: usize = 1;
    while (i < args.len) : (i += 1) {
        if (std.mem.eql(u8, args[i], "--root") and i + 1 < args.len) {
            i += 1;
            root_path = args[i];
        } else if (std.mem.eql(u8, args[i], "--check")) check = true;
    }
    var root = try std.Io.Dir.cwd().openDir(io, root_path, .{});
    defer root.close(io);
    const a = try root.readFileAlloc(io, "packages/platform/data/keysymdef.h", gpa, .limited(4 << 20));
    const b = try root.readFileAlloc(io, "packages/platform/data/XF86keysym.h", gpa, .limited(4 << 20));
    var defs: std.ArrayList(Def) = .empty;
    const xf86_from = try parseHeaders(gpa, a, b, &defs);
    const text = try render(gpa, defs.items, xf86_from);
    if (check) {
        const cur = root.readFileAlloc(io, out_path, gpa, .limited(16 << 20)) catch "";
        if (!std.mem.eql(u8, cur, text)) {
            std.debug.print("{s} is stale; run `zig build keysym-gen`\n", .{out_path});
            return 1;
        }
        return 0;
    }
    try root.writeFile(io, .{ .sub_path = out_path, .data = text });
    std.debug.print("wrote {s}: {d} definitions\n", .{ out_path, defs.items.len });
    return 0;
}

const testing = std.testing;

test "keysym-gen: parses keysymdef and XF86 lines" {
    const d = parseLine("#define XK_exclam                        0x0021  /* U+0021 EXCLAMATION MARK */", "XK_").?;
    try testing.expectEqualStrings("exclam", d.name);
    try testing.expectEqual(0x21, d.value);
    try testing.expectEqual(0x21, d.cp.?);
    const legacy = parseLine("#define XK_rightpointer                 0x0aeb  /*(U+261E WHITE RIGHT POINTING INDEX)*/", "XK_").?;
    try testing.expectEqual(0x261e, legacy.cp.?);
    const dep = parseLine("#define XK_Serbian_dze                   0x06af  /* deprecated */", "XK_").?;
    try testing.expect(dep.deprecated);
    try testing.expectEqual(null, dep.cp);
    const x = parseLine("#define XF86XK_ModeLock\t\t0x1008FF01\t/* Mode Switch Lock */", "XF86XK_").?;
    try testing.expectEqualStrings("ModeLock", x.name);
    try testing.expectEqual(0x1008ff01, x.value);
    const ev = parseLine("#define XF86XK_Macro1\t\t\t_EVDEVK(0x290)\t/* v5.5   KEY_MACRO1 */", "XF86XK_").?;
    try testing.expectEqual(0x10081290, ev.value);
    try testing.expectEqual(null, parseLine("/* Use: XF86XK_Eject _EVDEVK(0x0A2) */", "XF86XK_"));
    try testing.expectEqual(null, parseLine("#define XK_MISCELLANY", "XK_"));
}

test "keysym-gen: render prefers non-deprecated names and skips direct Unicode" {
    var arena: std.heap.ArenaAllocator = .init(testing.allocator);
    defer arena.deinit();
    const defs = [_]Def{
        .{ .name = "old", .value = 0x6af, .deprecated = true },
        .{ .name = "new", .value = 0x6af, .cp = 0x45f },
        .{ .name = "A", .value = 0x41, .cp = 0x41 },
        .{ .name = "Mute", .value = 0x1008ff12 },
    };
    const text = try render(arena.allocator(), &defs, 3);
    try testing.expect(std.mem.indexOf(u8, text, ".{ .name = \"new\", .value = 0x6af }") != null);
    try testing.expect(std.mem.indexOf(u8, text, "\"XF86Mute\"") != null);
    try testing.expect(std.mem.indexOf(u8, text, ".{ .keysym = 0x6af, .cp = 0x45f }") != null);
    try testing.expect(std.mem.indexOf(u8, text, ".{ .keysym = 0x41,") == null);
}
