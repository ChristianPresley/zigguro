//! shaderc: runs the shader programs of `packages/vulkan/src/shaders`
//! (E02.F05.S01.T02), validates each module with our structural
//! validator and writes `<name>.spv`, `<name>.spvasm` and `shaders.zig`
//! into the generated directory.
//!
//!   shaderc <out_dir> [--check]
//!
//! The output is checked in (like `vk.zig`), so the zg_vulkan package
//! embeds it without running the toolchain; with `--check` nothing is
//! written and the exit code is 1 when a file is stale (`zig build test`
//! runs this). A program that fails validation fails the build with
//! `<program>: <instruction> at word <n>: <issue>`.

const std = @import("std");
const spirv = @import("spirv");
const programs = @import("shader_programs");

const Program = spirv.dsl.Program;

pub fn main(init: std.process.Init) !u8 {
    const arena = init.arena.allocator();
    const io = init.io;
    const args = try init.minimal.args.toSlice(arena);
    var check = false;
    var out_dir: ?[]const u8 = null;
    for (args[1..]) |a| {
        if (std.mem.eql(u8, a, "--check")) check = true else out_dir = a;
    }
    const dir_path = out_dir orelse {
        std.log.err("usage: shaderc <out_dir> [--check]", .{});
        return 2;
    };
    var diag: std.Io.Writer.Allocating = .init(arena);
    const files = compile(arena, &programs.all, &diag.writer) catch |err| switch (err) {
        error.ShaderInvalid => {
            std.log.err("shader validation failed:\n{s}", .{diag.written()});
            return 1;
        },
        else => return err,
    };

    const cwd = std.Io.Dir.cwd();
    if (!check) try cwd.createDirPath(io, dir_path);
    var dir = try cwd.openDir(io, dir_path, .{});
    defer dir.close(io);
    var stale = false;
    for (files) |f| {
        if (check) {
            const current = dir.readFileAlloc(io, f.name, arena, .limited(16 << 20)) catch |err| switch (err) {
                error.FileNotFound => "",
                else => return err,
            };
            if (!std.mem.eql(u8, current, f.data)) {
                std.log.err("{s}/{s} is out of date; run `zig build shaderc`", .{ dir_path, f.name });
                stale = true;
            }
        } else try dir.writeFile(io, .{ .sub_path = f.name, .data = f.data });
    }
    return @intFromBool(stale);
}

pub const File = struct { name: []const u8, data: []const u8 };

/// Builds every program; on a validation issue writes
/// `<program>: <issue>` lines to `diag` and fails with `ShaderInvalid`
/// after checking every program. Allocates from `arena`.
pub fn compile(arena: std.mem.Allocator, list: []const Program, diag: *std.Io.Writer) ![]File {
    var files: std.ArrayList(File) = .empty;
    var index: std.Io.Writer.Allocating = .init(arena);
    const w = &index.writer;
    try w.writeAll(
        \\//! Generated by tools/shaderc from packages/vulkan/src/shaders/programs.zig.
        \\//! Do not edit; run `zig build shaderc`. Each declaration is a SPIR-V
        \\//! module (validated, 4-byte aligned) for `vkCreateShaderModule`.
        \\
        \\
    );
    var invalid = false;
    for (list) |p| {
        const s = try spirv.dsl.Shader.init(arena, p.stage);
        defer s.deinit();
        p.build(s) catch |err| {
            try diag.print("{s}: build failed: {t}\n", .{ p.name, err });
            invalid = true;
            continue;
        };
        const words = try s.finish();
        const issues = try spirv.validate.validate(arena, words, .vulkan_1_2);
        for (issues) |issue| try diag.print("{s}: {f}\n", .{ p.name, issue });
        if (issues.len > 0) {
            invalid = true;
            continue;
        }
        var text: std.Io.Writer.Allocating = .init(arena);
        try spirv.disasm.disassemble(arena, &text.writer, words);
        try files.append(arena, .{ .name = try std.fmt.allocPrint(arena, "{s}.spv", .{p.name}), .data = std.mem.sliceAsBytes(words) });
        try files.append(arena, .{ .name = try std.fmt.allocPrint(arena, "{s}.spvasm", .{p.name}), .data = text.written() });
        try w.print(
            \\pub const {s}: []align(4) const u8 = &{s}_spv;
            \\const {s}_spv align(4) = @embedFile("{s}.spv").*;
            \\
        , .{ p.name, p.name, p.name, p.name });
    }
    if (invalid) return error.ShaderInvalid;
    try files.append(arena, .{ .name = "shaders.zig", .data = index.written() });
    return files.toOwnedSlice(arena);
}

test "shaderc: every program builds and validates" {
    var arena: std.heap.ArenaAllocator = .init(std.testing.allocator);
    defer arena.deinit();
    var diag: std.Io.Writer.Allocating = .init(arena.allocator());
    const files = compile(arena.allocator(), &programs.all, &diag.writer) catch |err| {
        std.debug.print("{s}", .{diag.written()});
        return err;
    };
    try std.testing.expectEqual(programs.all.len * 2 + 1, files.len);
}

test "shaderc: an injected error names the program and instruction" {
    var arena: std.heap.ArenaAllocator = .init(std.testing.allocator);
    defer arena.deinit();
    const bad: Program = .{
        .name = "broken_frag",
        .stage = .fragment,
        .build = struct {
            fn build(s: *spirv.dsl.Shader) anyerror!void {
                // A conditional branch without OpSelectionMerge.
                const t = try s.c(bool, true);
                const a = s.m.newId();
                try s.f.op(.OpBranchConditional, &.{ t.id.word(), a.word(), a.word() });
                try s.f.label(a);
            }
        }.build,
    };
    var diag: std.Io.Writer.Allocating = .init(arena.allocator());
    try std.testing.expectError(error.ShaderInvalid, compile(arena.allocator(), &.{bad}, &diag.writer));
    try std.testing.expect(std.mem.indexOf(u8, diag.written(), "broken_frag: OpBranchConditional at word") != null);
    try std.testing.expect(std.mem.indexOf(u8, diag.written(), "missing OpSelectionMerge") != null);
}
