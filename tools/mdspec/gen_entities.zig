//! mdspec gen-entities: turns the HTML5 named character reference list
//! (`entities.json` in the WHATWG format) into the sorted table the
//! Markdown inline parser searches (E04.F06.S01.T03):
//!
//!   zig run tools/mdspec/gen_entities.zig -- \
//!     packages/gui/testdata/markdown/entities.json \
//!     > packages/gui/src/markdown/entities_table.zig
//!
//! Only names ending in `;` are kept (Markdown requires the semicolon).
//! No network: the JSON is checked in.

const std = @import("std");

const Entry = struct {
    name: []const u8,
    chars: []const u8,

    fn lt(_: void, a: Entry, b: Entry) bool {
        return std.mem.order(u8, a.name, b.name) == .lt;
    }
};

pub fn main(init: std.process.Init) !void {
    const gpa = init.gpa;
    const io = init.io;
    const args = try init.minimal.args.toSlice(init.arena.allocator());
    if (args.len != 2) {
        std.debug.print("usage: gen_entities <entities.json>\n", .{});
        std.process.exit(2);
    }
    const json = try std.Io.Dir.cwd().readFileAlloc(io, args[1], gpa, .limited(4 << 20));
    defer gpa.free(json);
    var parsed = try std.json.parseFromSlice(std.json.Value, gpa, json, .{});
    defer parsed.deinit();

    var list: std.ArrayList(Entry) = .empty;
    defer list.deinit(gpa);
    var it = parsed.value.object.iterator();
    while (it.next()) |kv| {
        const key = kv.key_ptr.*;
        if (key.len < 3 or key[0] != '&' or key[key.len - 1] != ';') continue;
        const chars = kv.value_ptr.object.get("characters").?.string;
        try list.append(gpa, .{ .name = key[1 .. key.len - 1], .chars = chars });
    }
    std.mem.sort(Entry, list.items, {}, Entry.lt);

    var buf: [4096]u8 = undefined;
    var fw = std.Io.File.stdout().writer(io, &buf);
    const w = &fw.interface;
    try w.writeAll(
        \\//! HTML5 named character references (generated by
        \\//! tools/mdspec/gen_entities.zig from
        \\//! packages/gui/testdata/markdown/entities.json; do not edit).
        \\//! Source: https://html.spec.whatwg.org/entities.json (WHATWG HTML
        \\//! Living Standard, CC-BY 4.0).
        \\
        \\pub const Entity = struct { name: []const u8, utf8: []const u8 };
        \\
        \\/// Sorted by name (byte order).
        \\pub const entities = [_]Entity{
        \\
    );
    for (list.items) |e| {
        try w.print("    .{{ .name = \"{s}\", .utf8 = \"", .{e.name});
        for (e.chars) |c| try w.print("\\x{x:0>2}", .{c});
        try w.writeAll("\" },\n");
    }
    try w.writeAll("};\n");
    try w.flush();
}
